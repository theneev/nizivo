// The other dist/ files, written from the same transforms as tokens.css (plan §7.1): the custom
// media, the Tailwind v4 `@theme` mapping and contract.json.
import type { Plugin, TokenTransformed } from '@terrazzo/parser';
import { FORMAT_ID } from '@terrazzo/plugin-css';
import { printJson } from '../scripts/figma/snapshot.ts';
import {
  BASE_INPUT,
  LAYERS,
  PREFIX,
  breakpointQuery,
  currentResolver,
  subValueVariableName,
} from './css.ts';

const HEADER = '/* Generated by the @nizivo/tokens build. Do not edit. */';

interface Breakpoint {
  name: string;
  query: string;
  provisional: boolean;
}

/** The breakpoints, smallest first; `lg` is provisional until design confirms it (plan §7.6). */
function breakpoints(): Breakpoint[] {
  return ['sm', 'lg'].map((name) => {
    const token = currentResolver().apply({})[`breakpoint.${name}`];
    const provisional = token?.$extensions?.['app.nizivo.status'] === 'provisional';
    return { name: `--${PREFIX}-${name}`, query: breakpointQuery(name), provisional };
  });
}

/** `@custom-media --nz-sm (width >= 40rem);` for consumers who build with Lightning CSS or PostCSS. */
export function customMedia({ filename }: { filename: string }): Plugin {
  return {
    name: 'nizivo:custom-media',
    enforce: 'post',
    build({ outputFile }) {
      const lines = breakpoints().map(({ name, query, provisional }) =>
        provisional
          ? `/* Provisional: outside semver until design confirms the threshold. */\n@custom-media ${name} ${query};`
          : `@custom-media ${name} ${query};`,
      );
      outputFile(filename, `${HEADER}\n${lines.join('\n')}\n`);
    },
  };
}

/** `--<namespace>-nz-<name>: var(--nz-…);` for every transform whose id matches `group`. */
function themeEntries(
  transforms: TokenTransformed[],
  namespace: string,
  group: RegExp,
  strip: RegExp,
): string[] {
  return transforms
    .filter((t) => group.test(t.id))
    .toSorted((a, b) => (a.id < b.id ? -1 : 1))
    .map(
      (t) =>
        `  --${namespace}-${PREFIX}-${t.id.replace(strip, '').replaceAll('.', '-')}: var(${t.localID});`,
    );
}

/**
 * Tailwind v4 (plan §7.8): `@theme inline` entries that point at the semantic variables, never at
 * primitives, so utilities follow nested themes. Breakpoints are literal, because a media query
 * cannot read a variable.
 */
export function tailwind({ filename }: { filename: string }): Plugin {
  return {
    name: 'nizivo:tailwind',
    enforce: 'post',
    build({ getTransforms, outputFile }) {
      const base = getTransforms({ format: FORMAT_ID, input: BASE_INPUT });
      const lines = [
        ...themeEntries(base, 'color', /^color\.(bg|text|border|icon|chart)\./, /^color\./),
        ...themeEntries(base, 'radius', /^radius\./, /^radius\./),
        ...themeEntries(base, 'shadow', /^elevation\./, /^elevation\./),
        ...themeEntries(base, 'ease', /^easing\./, /^easing\./),
        ...breakpoints().map(
          ({ name, query }) =>
            `  --breakpoint-${name.slice(2)}: ${/\(width >= (.+)\)/.exec(query)?.[1]};`,
        ),
      ];
      outputFile(filename, `${HEADER}\n@theme inline {\n${lines.join('\n')}\n}\n`);
    },
  };
}

interface ContractEntry {
  token?: string;
  type: string;
  public: boolean;
  part?: string;
}

/**
 * contract.json: every custom property tokens.css declares, with its token, type and whether it is
 * public (`--nz-p-*` primitives are not), plus the prefix, layers and custom media (plan §5.2, §7.3).
 */
export function contract({ filename }: { filename: string }): Plugin {
  return {
    name: 'nizivo:contract',
    enforce: 'post',
    build({ getTransforms, outputFile }) {
      const variables = new Map<string, ContractEntry>([
        [`--${PREFIX}-css-version`, { type: 'string', public: true }],
      ]);
      const add = (name: string, entry: ContractEntry): void => {
        const known = variables.get(name);
        if (known && known.token !== entry.token) {
          throw new Error(`${name} is declared by ${known.token} and ${entry.token}`);
        }
        variables.set(name, entry);
      };
      for (const t of getTransforms({ format: FORMAT_ID, input: BASE_INPUT })) {
        if (!t.localID) continue;
        const entry = { token: t.id, type: t.token.$type, public: !t.id.startsWith('color.p.') };
        add(t.localID, entry);
        if (t.type === 'MULTI_VALUE') {
          for (const part of Object.keys(t.value))
            add(subValueVariableName(t.localID, part), { ...entry, part });
        }
      }
      outputFile(
        filename,
        printJson({
          $comment: 'Generated by the @nizivo/tokens build. Do not edit.',
          package: '@nizivo/tokens',
          prefix: PREFIX,
          layer: 'nz.tokens',
          layers: LAYERS,
          customMedia: Object.fromEntries(
            breakpoints().map(({ name, query, provisional }) => [
              name,
              provisional ? { query, status: 'provisional' } : { query },
            ]),
          ),
          variables: Object.fromEntries(
            [...variables].toSorted(([a], [b]) => a.localeCompare(b, 'en-US', { numeric: true })),
          ),
        }),
      );
    },
  };
}
