// tokens.json and the js-refs "." entry (plan §5.2, §7.1): both written from the resolved set in
// resolve.ts, so they agree with tokens.css. The shapes are documented in TOKENS-JSON.md.
import type { Plugin } from '@terrazzo/parser';
import { printJson } from '../scripts/figma/snapshot.ts';
import { breakpointQuery, currentResolver } from './css.ts';
import {
  type ContextValue,
  type ResolvedSet,
  type ResolvedToken,
  resolveTokens,
} from './resolve.ts';

const HEADER = 'Generated by the @nizivo/tokens build. Do not edit.';

/** The version of the tokens.json shape; a breaking change to it bumps this (TOKENS-JSON.md). */
export const TOKENS_JSON_FORMAT = 1;

const isRecord = (value: unknown): value is Record<string, unknown> =>
  typeof value === 'object' && value !== null && !Array.isArray(value);

/** One token as tokens.json prints it: fixed field order, optional fields only when set. */
function jsonEntry(token: ResolvedToken): Record<string, unknown> {
  const { id: _id, modes, ...rest } = token;
  const out: Record<string, unknown> = {
    type: rest.type,
    cssVariable: rest.cssVariable,
    public: rest.public,
    value: rest.value,
    provenance: rest.provenance,
  };
  if (rest.aliasOf) out['aliasOf'] = rest.aliasOf;
  if (Object.keys(modes).length > 0) out['modes'] = modes;
  for (const key of [
    'parts',
    'customMedia',
    'status',
    'deprecated',
    'description',
    'figma',
  ] as const) {
    if (rest[key] !== undefined) out[key] = rest[key];
  }
  return out;
}

/**
 * dist/tokens.json: every token (primitives and the never-emitted breakpoints and frame widths
 * included, marked by `public` and `cssVariable`), its literal value in the default context, and the
 * contexts where it differs (TOKENS-JSON.md).
 */
export function tokensJson({ filename }: { filename: string }): Plugin {
  return {
    name: 'nizivo:tokens-json',
    enforce: 'post',
    build({ getTransforms, outputFile }) {
      const { modifiers, tokens } = resolveTokens(getTransforms);
      outputFile(
        filename,
        printJson({
          $comment: `${HEADER} Shape: packages/tokens/TOKENS-JSON.md in the nizivo repository.`,
          format: TOKENS_JSON_FORMAT,
          package: '@nizivo/tokens',
          prefix: currentPrefix(tokens),
          modifiers,
          tokens: Object.fromEntries(tokens.map((token) => [token.id, jsonEntry(token)])),
        }),
      );
    },
  };
}

/** The prefix, read back from a declared variable so it cannot disagree with tokens.css. */
function currentPrefix(tokens: ResolvedToken[]): string {
  const name = tokens.find((t) => t.cssVariable)?.cssVariable ?? '';
  const prefix = /^--([a-z0-9]+)-/.exec(name)?.[1];
  if (!prefix) throw new Error('No declared variable to read the prefix from');
  return prefix;
}

