// The "." entry

/** `border-width` → `borderWidth`; `0-5` → `0.5`, so `space[0.5]` reads like Figma's `space/0.5`. */
const camel = (text: string): string =>
  text
    .replaceAll(/(\d)-(?=\d)/g, '$1.')
    .replaceAll(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase());

/** `color.bg.surface` → `['color', 'bgSurface']`; `font.label.m` → `['font', 'labelM']`. */
export function refPath(id: string): [group: string, key: string] {
  const [group = '', ...rest] = id.split('.');
  return [camel(group), camel(rest.join('-'))];
}

const IDENTIFIER = /^[A-Za-z_$][\w$]*$/;
const property = (key: string): string => (IDENTIFIER.test(key) ? key : JSON.stringify(key));

/** A value for a doc comment: one line, never closing the comment. */
const shown = (value: ContextValue['value']): string =>
  (typeof value === 'string' ? value : value.font).replaceAll('*/', '*\\/');

function docLines(token: ResolvedToken, variable: string): string[] {
  const values = [`\`${shown(token.value)}\``];
  for (const contexts of Object.values(token.modes)) {
    for (const [name, entry] of Object.entries(contexts))
      values.push(`${name} \`${shown(entry.value)}\``);
  }
  const lines = [`\`${variable}\` (${token.type}): ${values.join(' · ')}`];
  if (token.description) lines.push(token.description.replaceAll('*/', '*\\/'));
  if (token.status) lines.push(`Status: ${token.status}.`);
  if (token.deprecated)
    lines.push(`@deprecated${token.deprecated === true ? '' : ` ${token.deprecated}`}`);
  return lines;
}

const docComment = (lines: string[], indent: string): string =>
  lines.length === 1
    ? `${indent}/** ${lines[0]} */`
    : `${indent}/**\n${lines.map((line) => `${indent} * ${line}`).join('\n')}\n${indent} */`;

interface Ref {
  key: string;
  /** A `var()` string, or a typography token's parts as `var()` strings. */
  ref: string | Record<string, string>;
  doc: string[];
}

const jsValue = (ref: Ref['ref']): string =>
  typeof ref === 'string'
    ? JSON.stringify(ref)
    : `{ ${Object.entries(ref)
        .map(([part, value]) => `${part}: ${JSON.stringify(value)}`)
        .join(', ')} }`;

const typeValue = (ref: Ref['ref']): string =>
  typeof ref === 'string'
    ? JSON.stringify(ref)
    : `{ ${Object.entries(ref)
        .map(([part, value]) => `readonly ${part}: ${JSON.stringify(value)}`)
        .join('; ')} }`;

interface Group {
  name: string;
  doc: string;
  refs: Ref[];
}

/** The `var()` groups, the typography parts, and every public variable they reference. */
function refGroups(tokens: ResolvedToken[]): { groups: Group[]; variables: string[] } {
  const groups = new Map<string, Ref[]>();
  const typography: Ref[] = [];
  const variables: string[] = [];
  const add = (group: string, ref: Ref) => {
    const refs = groups.get(group) ?? [];
    if (refs.some((r) => r.key === ref.key))
      throw new Error(`Two tokens map to ${group}.${ref.key}`);
    groups.set(group, [...refs, ref]);
  };
  for (const token of tokens) {
    if (!token.public || !token.cssVariable) continue;
    const [group, key] = refPath(token.id);
    add(group, { key, ref: `var(${token.cssVariable})`, doc: docLines(token, token.cssVariable) });
    variables.push(token.cssVariable);
    if (token.parts) {
      const parts = Object.entries(token.parts);
      variables.push(...parts.map(([, name]) => name));
      typography.push({
        key,
        ref: Object.fromEntries(parts.map(([part, name]) => [part, `var(${name})`])),
        doc: [
          `The parts of \`${token.cssVariable}\`; \`letterSpacing\` is the tracking the shorthand leaves out.`,
        ],
      });
    }
  }
  if (groups.has('typography')) throw new Error('A token group is named typography');
  const out = [...groups].map(([name, refs]) => ({
    name,
    refs,
    doc: `\`var()\` references to the ${name} tokens.`,
  }));
  out.push({
    name: 'typography',
    refs: typography,
    doc: "Each text style's parts as `var()` references, for when the `font` shorthand is not enough.",
  });
  return {
    groups: out.toSorted((a, b) => (a.name < b.name ? -1 : 1)),
    variables: variables.toSorted(),
  };
}

interface Spring {
  key: string;
  physics: Record<string, number>;
}

/** The Figma `spring()` parameters behind `--nz-easing-spring*`, for JS animation libraries. */
function springs(): Spring[] {
  const out: Spring[] = [];
  for (const token of Object.values(currentResolver().apply({}))) {
    const spring = token.$extensions?.['dev.nizivo.spring'];
    if (!isRecord(spring)) continue;
    const physics: Record<string, number> = {};
    for (const name of ['mass', 'stiffness', 'damping', 'velocity']) {
      const value = spring[name];
      if (typeof value !== 'number') throw new Error(`${token.id}: spring ${name} is not a number`);
      physics[name] = value;
    }
    out.push({ key: refPath(token.id)[1], physics });
  }
  return out.toSorted((a, b) => (a.key < b.key ? -1 : 1));
}

interface Breakpoint {
  key: string;
  query: string;
  status?: string;
}

/** The breakpoints, as custom-media.css prints their queries. */
function breakpoints(tokens: ResolvedToken[]): Breakpoint[] {
  const out: Breakpoint[] = [];
  for (const token of tokens) {
    if (!token.customMedia) continue;
    const key = token.id.slice('breakpoint.'.length);
    const breakpoint: Breakpoint = { key, query: breakpointQuery(key) };
    if (token.status) breakpoint.status = token.status;
    out.push(breakpoint);
  }
  return out;
}

const union = (names: string[]): string =>
  names.length === 0 ? 'never' : `\n${names.map((n) => `  | ${JSON.stringify(n)}`).join('\n')}`;

/** The tokens.json shape, as types (TOKENS-JSON.md). */
const TOKENS_JSON_TYPES = `/** Where a token's value comes from in a context (TOKENS-JSON.md). */
export type TokenProvenance = 'figma' | 'code-owned' | 'override' | 'proposal';

/** A typography token's value: the \`font\` shorthand and its parts. */
export interface TokenTypographyValue {
  font: string;
  fontFamily: string;
  fontSize: string;
  fontWeight: string;
  lineHeight: string;
  letterSpacing: string;
}

/** A token's value in one context. */
export interface TokenContextValue {
  value: string | TokenTypographyValue;
  provenance: TokenProvenance;
  aliasOf?: string;
}

/** One entry of \`@nizivo/tokens/tokens.json\`; the top-level value is the default context's. */
export interface TokenEntry extends TokenContextValue {
  type: string;
  cssVariable: string | null;
  public: boolean;
  /** Per modifier, the contexts whose entry differs from the default one. */
  modes?: Record<string, Record<string, TokenContextValue>>;
  parts?: Record<string, string>;
  customMedia?: string;
  status?: string;
  deprecated?: string | true;
  description?: string;
  figma?: { name: string; variableId?: string; styleId?: string };
}

/** \`@nizivo/tokens/tokens.json\`. A JSON import widens literals, so cast it: \`data as TokensJson\`. */
export interface TokensJson {
  $comment: string;
  format: ${TOKENS_JSON_FORMAT};
  package: '@nizivo/tokens';
  prefix: string;
  modifiers: Record<string, { contexts: string[]; default: string }>;
  tokens: Record<TokenId, TokenEntry>;
}`;

/** dist/index.js and dist/index.d.ts: typed `var()` references, breakpoints and spring physics. */
export function jsRefs({ filename }: { filename: string }): Plugin {
  const base = filename.replace(/\.js$/, '');
  return {
    name: 'nizivo:js-refs',
    enforce: 'post',
    build({ getTransforms, outputFile }) {
      const resolved: ResolvedSet = resolveTokens(getTransforms);
      const { groups, variables } = refGroups(resolved.tokens);
      const bps = breakpoints(resolved.tokens);
      const sprs = springs();
      const js: string[] = [`// ${HEADER} Typed var() references: TOKENS-JSON.md.`];
      const dts: string[] = [`// ${HEADER}`];
      for (const group of groups) {
        js.push(`export const ${group.name} = {`);
        dts.push(`/** ${group.doc} */`, `export declare const ${group.name}: {`);
        for (const { key, ref, doc } of group.refs) {
          js.push(`  ${property(key)}: ${jsValue(ref)},`);
          dts.push(docComment(doc, '  '), `  readonly ${property(key)}: ${typeValue(ref)};`);
        }
        js.push('};');
        dts.push('};');
      }
      js.push('export const breakpoints = {');
      dts.push(
        '/** Media queries for `matchMedia()`, equal to custom-media.css. */',
        'export declare const breakpoints: {',
      );
      for (const { key, query, status } of bps) {
        js.push(`  ${property(key)}: ${JSON.stringify(query)},`);
        if (status)
          dts.push(
            `  /** Status: ${status}; outside semver until design confirms the threshold. */`,
          );
        dts.push(`  readonly ${property(key)}: ${JSON.stringify(query)};`);
      }
      js.push('};', 'export const springs = {');
      dts.push(
        '};',
        '/** Figma `spring(mass, stiffness, damping, velocity)` behind the `easing.spring*` tokens. */',
        'export declare const springs: {',
      );
      for (const { key, physics } of sprs) {
        const body = Object.entries(physics).map(([name, value]) => `${name}: ${value}`);
        js.push(`  ${property(key)}: { ${body.join(', ')} },`);
        dts.push(
          `  readonly ${property(key)}: { ${body.map((b) => `readonly ${b}`).join('; ')} };`,
        );
      }
      js.push('};');
      dts.push(
        '};',
        '/** Every public token variable tokens.css declares, for `style.setProperty()` and the like. */',
        `export type CssVariable =${union(variables)};`,
        '/** Every token id in tokens.json. */',
        `export type TokenId =${union(resolved.tokens.map((t) => t.id))};`,
        TOKENS_JSON_TYPES,
      );
      outputFile(`${base}.js`, `${js.join('\n')}\n`);
      outputFile(`${base}.d.ts`, `${dts.join('\n')}\n`);
    },
  };
}
