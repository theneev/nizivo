// `pnpm tokens:spring`: Figma `spring(m, k, c, v)` easings → src/code-owned/motion-derived.tokens.json.
// `pnpm tokens:spring:check`: fails when the committed file differs from what the generator derives.
//
// The one generator (@nizivo/tooling/spring, plan §13.1) turns each easing that carries
// `$extensions["dev.nizivo.spring"]` into a `linear()` easing and its paired settle duration. The
// file is a source of the motion `default` context, after the Figma file, so the `linear()` replaces
// the normalizer's cubic-bezier stand-in. Reduced mode keeps Figma's linear easings and takes its
// spring durations from code-owned/motion/reduced.tokens.json.
//
// Usage: node scripts/spring.ts [--check]
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { springToCss, type Spring } from '@nizivo/tooling/spring';
import { PACKAGE_ROOT, isRecord, printJson } from './figma/snapshot.ts';
import { walkTokens, type Group } from './normalize/json.ts';

export const MOTION_DEFAULT: string = resolve(
  PACKAGE_ROOT,
  'src/figma-owned/motion/default.tokens.json',
);
export const MOTION_DERIVED: string = resolve(
  PACKAGE_ROOT,
  'src/code-owned/motion-derived.tokens.json',
);

const GENERATOR = '@nizivo/tooling/spring';

function isSpring(value: unknown): value is Spring {
  return (
    isRecord(value) &&
    ['mass', 'stiffness', 'damping', 'velocity'].every((key) => typeof value[key] === 'number')
  );
}

/** The derived tokens for every spring easing in `motionDefault` (the parsed Figma file). */
export function deriveSprings(motionDefault: Record<string, unknown>): Group {
  const easing: Group = {};
  const duration: Group = {};
  walkTokens(motionDefault, (path, token) => {
    const extensions = isRecord(token.$extensions) ? token.$extensions : {};
    const spring = extensions['dev.nizivo.spring'];
    if (spring === undefined) return;
    if (path[0] !== 'easing' || path.length !== 2 || !isSpring(spring)) {
      throw new Error(
        `${path.join('.')}: a spring must be easing.<name> with mass/stiffness/damping/velocity`,
      );
    }
    const name = path[1] ?? '';
    const { mass, stiffness, damping, velocity } = spring;
    const css = springToCss({ mass, stiffness, damping, velocity });
    const derived = {
      from: path.join('.'),
      generator: GENERATOR,
      spring: { mass, stiffness, damping, velocity },
    };
    easing[name] = {
      $type: 'string',
      $value: css.easing,
      $extensions: {
        'app.nizivo.derived': {
          ...derived,
          points: css.points,
          maxError: css.maxError,
          overshootPct: css.overshootPct,
        },
      },
    };
    duration[name] = {
      $type: 'duration',
      $value: { value: css.durationMs, unit: 'ms' },
      $extensions: { 'app.nizivo.derived': derived },
    };
  });
  if (Object.keys(easing).length === 0)
    throw new Error('No spring easings found in the Figma motion file');
  return {
    $description: 'Generated by scripts/spring.ts from the Figma spring() easings. Do not edit.',
    duration,
    easing,
  };
}

export function renderDerived(): string {
  const motionDefault: unknown = JSON.parse(readFileSync(MOTION_DEFAULT, 'utf8'));
  if (!isRecord(motionDefault)) throw new Error(`${MOTION_DEFAULT}: not a JSON object`);
  return printJson(deriveSprings(motionDefault));
}

function run(check: boolean): number {
  const expected = renderDerived();
  if (check) {
    let current = '';
    try {
      current = readFileSync(MOTION_DERIVED, 'utf8');
    } catch {
      // A missing file is reported below like a stale one.
    }
    if (current === expected) {
      console.log('src/code-owned/motion-derived.tokens.json matches the spring generator');
      return 0;
    }
    console.error('src/code-owned/motion-derived.tokens.json is stale. Run pnpm tokens:spring.');
    return 1;
  }
  writeFileSync(MOTION_DERIVED, expected);
  console.log('Wrote src/code-owned/motion-derived.tokens.json');
  return 0;
}

if (import.meta.main) {
  process.exitCode = run(process.argv.includes('--check'));
}
