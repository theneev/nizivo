/**
 * Text and ordering rules shared by every `contracts/api` file (API-JSON.md, "Determinism"), and
 * the JSDoc reader. Pure.
 */
import { printJson } from '../gen/format.ts';
import type { Deprecation, GeneratedComment } from './schema.ts';

export const GENERATED_COMMENT: GeneratedComment = 'generated by nz api; do not edit';

/** Code-point order (`localeCompare` depends on the machine's locale). */
export function compareStrings(a: string, b: string): number {
  return a < b ? -1 : a > b ? 1 : 0;
}

/** Sorts object keys in code-point order at every depth; arrays keep their order. */
export function sortKeys(value: unknown): unknown {
  if (Array.isArray(value)) return value.map(sortKeys);
  if (typeof value === 'object' && value !== null) {
    return Object.fromEntries(
      Object.entries(value)
        .filter(([, item]) => item !== undefined)
        .toSorted(([a], [b]) => compareStrings(a, b))
        .map(([key, item]) => [key, sortKeys(item)]),
    );
  }
  return value;
}

/** A generated file's content: keys sorted, printed as `nz gen` prints JSON (oxfmt's style). */
export function printApiJson(value: unknown): string {
  return printJson(sortKeys(value));
}

const FENCE = /^(```|~~~)/;
const LIST_ITEM = /^(?:[-*+]|\d+[.)])\s/;

/**
 * Comment text as Markdown, so rewrapping a comment changes nothing: the lines of a paragraph are
 * joined with one space, paragraphs are separated by `\n\n`, and the result is trimmed. A line that
 * starts a list item (`- `, `* `, `1. `) starts a new line instead, and fenced code keeps its lines.
 */
export function normalizeText(source: string): string {
  const paragraphs: string[] = [];
  let current: string[] = [];
  let fence: string[] | undefined;
  const flush = () => {
    if (current.length > 0) paragraphs.push(current.join(''));
    current = [];
  };
  for (const raw of source.split('\n')) {
    if (fence !== undefined) {
      fence.push(raw.trimEnd());
      if (FENCE.test(raw.trim())) {
        paragraphs.push(fence.join('\n'));
        fence = undefined;
      }
      continue;
    }
    const line = raw.trim();
    if (FENCE.test(line)) {
      flush();
      fence = [line];
    } else if (line === '') {
      flush();
    } else if (current.length === 0) {
      current.push(line);
    } else {
      current.push(LIST_ITEM.test(line) ? `\n${line}` : ` ${line}`);
    }
  }
  if (fence !== undefined) paragraphs.push(fence.join('\n'));
  flush();
  return paragraphs.join('\n\n').trim();
}

/** What `contracts/api` keeps of a JSDoc comment. */
export interface DocComment {
  description?: string;
  /** The `@default` text, verbatim. */
  default?: string;
  deprecated?: Deprecation;
  /** `@param` descriptions by parameter name. */
  params: Map<string, string>;
  returns?: string;
}

/**
 * Tags `contracts/api` recognises. A tag starts at `@name` after white space, also mid-line:
 * TypeScript's parser reads `/** 32 px. @default 'md' *\/` as plain text, but the tag is meant.
 * An `@` that starts anything else (`@nizivo/react`) stays text.
 */
const TAGS = new Set([
  'default',
  'defaultValue',
  'deprecated',
  'param',
  'returns',
  'return',
  'example',
  'see',
  'since',
  'remarks',
  'privateRemarks',
  'internal',
  'throws',
  'typeParam',
]);

/** Parses a `/** … *\/` comment. */
export function parseDocComment(raw: string): DocComment {
  const body = raw
    .replace(/^\/\*\*/, '')
    .replace(/\*\/$/, '')
    .split('\n')
    .map((line) => line.replace(/^\s*\*(?!\/) ?/, ''))
    .join('\n');
  const starts: { index: number; tag: string }[] = [];
  for (const match of body.matchAll(/(^|\s)@([A-Za-z]+)\b/g)) {
    const tag = match[2] ?? '';
    if (TAGS.has(tag)) starts.push({ index: match.index + (match[1] ?? '').length, tag });
  }
  const doc: DocComment = { params: new Map() };
  const description = normalizeText(body.slice(0, starts[0]?.index ?? body.length));
  if (description !== '') doc.description = description;
  starts.forEach(({ index, tag }, position) => {
    const end = starts[position + 1]?.index ?? body.length;
    const content = normalizeText(body.slice(index + 1 + tag.length, end));
    if (tag === 'default' || tag === 'defaultValue') doc.default = content;
    else if (tag === 'deprecated') doc.deprecated = content === '' ? true : content;
    else if (tag === 'returns' || tag === 'return') {
      if (content !== '') doc.returns = content;
    } else if (tag === 'param') {
      const param = /^(?:\{[^}]*\}\s*)?\[?([\w$.]+)[^\s\]]*\]?\s*(?:-\s*)?([\s\S]*)$/.exec(content);
      if (param?.[1] !== undefined && param[2] !== undefined && param[2] !== '') {
        doc.params.set(param[1], param[2]);
      }
    }
  });
  return doc;
}
