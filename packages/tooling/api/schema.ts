/**
 * The `contracts/api/**` format (ARCHITECTURE.md §6, §8.4, §18.1, §18.2): what `nz api` writes from
 * the built `@nizivo/react`, and what `apps/docs` renders into props, parts, data attribute and
 * hook tables. Types only, with no imports and no runtime code, so any package can import it with
 * `import type`. `API-JSON.md` next to this file is the field reference, with full examples.
 *
 * Two kinds of file:
 * - `contracts/api/react/<entry>.json` ({@link ReactApiFile}), one per JavaScript entry of the
 *   `@nizivo/react` exports map: `./alert` → `react/alert.json`, `./unstable/<name>` →
 *   `react/unstable/<name>.json`, and the root barrel `.` → `react/index.json`.
 * - `contracts/api/css/<name>.json` ({@link CssApiFile}), one per stylesheet entry:
 *   `./css/<name>.css` → `css/<name>.json` (and `./reset.css` → `css/reset.json` once it exists).
 *   `./styles.css` gets none: it concatenates the others.
 *
 * Determinism (both files): keys sorted in code-point order at every depth (so `$comment` comes
 * first), arrays sorted as each field says, printed by `printJson` in `../gen/format.ts` (oxfmt's
 * style), LF line endings and a final newline. No timestamps, no absolute paths, no package versions.
 */

// ── Shared ──────────────────────────────────────────────────────────────────────────────────────

/** The header of every generated file; the same phrasing as `nz gen` (`design/component-map.json`). */
export type GeneratedComment = 'generated by nz api; do not edit';

/** Version of this file format, not of the package. Bump it on any breaking change to these types. */
export type ApiFormatVersion = 1;

/** A JSDoc `@deprecated` tag: its text, or `true` when the tag has no text. */
export type Deprecation = string | true;

/** A literal member of a union, as a JSON value (`"info"`, `2`, `true`, `null`). */
export type LiteralValue = string | number | boolean | null;

// ── contracts/api/react/<entry>.json ───────────────────────────────────────────────────────────

export interface ReactApiFile {
  $comment: GeneratedComment;
  version: ApiFormatVersion;
  package: '@nizivo/react';
  /** The exports-map key: `"."`, `"./alert"`, `"./unstable/date-range-picker"`. */
  entry: string;
  /**
   * From `src/<name>/component.json`. Absent for an entry without a manifest (`"."`, `"./config"`,
   * `"./contracts"`, `"./augment"`).
   */
  component?: ComponentInfo;
  /** Every runtime and type export of the entry, sorted by `name`. */
  exports: ApiExport[];
  /** Every element the entry's components render with a `data-slot`, sorted by `slot`. */
  slots: SlotInfo[];
}

/** What `component.json` says about the entry (§6, `packages/tooling/gen/COMPONENT-JSON.md`). */
export interface ComponentInfo {
  /** The manifest `name` (kebab-case): `"alert"`. */
  name: string;
  status: 'stable' | 'unstable';
  /** §9.5: `server` (T0, server-safe), `client` (T0 in thin client leaves), `engine` (T1), `own` (T2). */
  tier: 'server' | 'client' | 'engine' | 'own';
  /** The behaviour engine family (`"react-aria"`); only on tier `engine`. */
  engine?: string;
  /** Present and `true` for the overlay family (§12). */
  overlay?: true;
  /** The stylesheet's exports key (`"./css/alert.css"`), described by `css/<name>.json`. */
  stylesheet?: string;
  /** The manifest `cssDeps`, sorted. */
  cssDeps: string[];
  /** The manifest `variants`: keys sorted, each value list in manifest (Figma) order. */
  variants: Record<string, string[]>;
}

export type ApiExportKind =
  /** A standalone component function: `Alert`, `AlertDismiss`, `Button`, `NizivoConfig`. */
  | 'component'
  /** The namespace object of a compound component (`Card`, `Select`), used as `Card.Root`. */
  | 'namespace'
  /** The flat name of a compound part (`CardRoot`); documented once, under its namespace. */
  | 'part'
  /** A React hook (`use*`). */
  | 'hook'
  /** Any other function: `mergeProps`, `stateAttrs`. */
  | 'function'
  /** A non-function value: `STATE_ATTR_NAMES`. */
  | 'constant'
  /** An interface or type alias (`import type`). */
  | 'type';

export type ApiExport =
  | ComponentExport
  | NamespaceExport
  | PartExport
  | FunctionExport
  | ConstantExport
  | TypeExport
  | ReexportedExport;

export interface ExportBase {
  name: string;
  kind: ApiExportKind;
  /**
   * The line a consumer writes, with no semicolon: `import { Alert } from '@nizivo/react/alert'`,
   * or `import type { AlertProps } from '@nizivo/react/alert'` for a type.
   */
  import: string;
  /**
   * The JSDoc text without its tags, as Markdown: the comment's lines joined with one space,
   * paragraph breaks kept as `\n\n`, trimmed (so rewrapping a comment changes nothing). A line that
   * starts a list item (`- `, `* `, `1. `) starts a new line (`\n`) instead, and fenced code keeps
   * its lines. Absent when there is none. Every `description` in these files follows the same rule.
   */
  description?: string;
  deprecated?: Deprecation;
  /** Only a {@link ReexportedExport} has it, so `export.definedIn !== undefined` narrows to one. */
  definedIn?: never;
}

/** Shared by standalone components and compound parts. */
export interface ComponentDoc {
  /**
   * `true` when the declaring module starts with `'use client'` (a client reference under RSC: read
   * it from the built `.js`, because `.d.ts` files drop directives); `false` when it is server-safe.
   */
  client: boolean;
  /** The exported props interface (`"AlertProps"`); its own type export then omits `members`. */
  propsType: string;
  /**
   * The props the interface declares itself, plus the members of any base interface declared in
   * `@nizivo/react` (marked `inheritedFrom`). React's DOM props are summarised in `inherits`. Sorted
   * by `name`.
   */
  props: MemberDoc[];
  /** One entry per base in the `extends` clause that is summarised rather than listed; clause order. */
  inherits: InheritedProps[];
  /** Present when the component takes a `render` prop (§10.1). */
  render?: RenderDoc;
  /**
   * The `data-slot` of the element the component renders as its root (`"alert"`; `Select.Root` is
   * `"select"`, the element the engine renders around the trigger). The root is the element the
   * component's `return` renders, through wrappers such as a context provider, or the props object
   * it passes to `renderElement()`; for an engine part, the element the part names with its own
   * class (`Dialog.Popup` → `dialog-popup`, while `dialog-positioner` and `dialog-backdrop` are
   * inner slots). Absent for a component with no element of its own (`Dialog.Root`,
   * `Tooltip.Root`, `NizivoConfig`).
   */
  slot?: string;
  /** The repo-relative source file: `"packages/react/src/alert/alert.tsx"`. */
  source: string;
}

export interface ComponentExport extends ExportBase, ComponentDoc {
  kind: 'component';
}

export interface NamespaceExport extends ExportBase {
  kind: 'namespace';
  /** The parts in the order of the manifest's `parts` (the order is meaningful: `Root` first). */
  parts: PartDoc[];
}

export interface PartDoc extends ComponentDoc {
  /** The member name used through the namespace: `"Root"` in `Card.Root`. */
  name: string;
  /** The flat export of the same component: `"CardRoot"`. */
  flatName: string;
  description?: string;
  deprecated?: Deprecation;
}

/** A flat part export. Its documentation is the `PartDoc` that `partOf` names. */
export interface PartExport extends ExportBase {
  kind: 'part';
  /** `"Card.Root"`: the namespace export and the part's member name. */
  partOf: string;
}

export interface FunctionExport extends ExportBase {
  kind: 'function' | 'hook';
  /** As on {@link ComponentDoc.client}. */
  client: boolean;
  /** One per overload, in declaration order. */
  signatures: SignatureDoc[];
  source: string;
}

export interface SignatureDoc {
  /**
   * The declaration as written in the `.d.ts`, without `export declare` and the final semicolon:
   * `function stateAttrs(input: StateInput): StateAttrs`.
   */
  text: string;
  /** In positional order (never sorted). */
  parameters: ParameterDoc[];
  returns: { type: string; description?: string };
}

export interface ParameterDoc {
  name: string;
  /** As written in the `.d.ts`. */
  type: string;
  optional: boolean;
  /** Present and `true` for a rest parameter (`...sources`); `name` is without the dots. */
  rest?: true;
  /** From the JSDoc `@param`. */
  description?: string;
}

export interface ConstantExport extends ExportBase {
  kind: 'constant';
  client: boolean;
  /** The declared type as written in the `.d.ts`: `readonly string[]`. */
  type: string;
  source: string;
}

export interface TypeExport extends ExportBase {
  kind: 'type';
  declaration: 'interface' | 'type';
  /** Type parameters as written: `["S"]` for `RenderProp<S>`. Empty when there are none. */
  typeParameters: string[];
  /** For a type alias: its right-hand side as written in the `.d.ts`. */
  text?: string;
  /** For a type that resolves to literals only; see {@link MemberDoc.values}. */
  values?: LiteralValue[];
  /** The `extends` clause of an interface, each base as written; clause order. */
  extends?: string[];
  /**
   * For an interface that is neither a props nor a state interface: its own members, sorted by
   * `name`. Labels interfaces (`AlertDismissLabels`) and augmentation maps (`ButtonVariantMap`) list
   * them here.
   */
  members?: MemberDoc[];
  /** The props interface of this export or part (`"Alert"`, `"Card.Root"`): documented there. */
  propsOf?: string;
  /** The render state of this export or part (`"Alert"`): documented in its `render`. */
  stateOf?: string;
  source: string;
}

/**
 * An export documented in another entry's file: every export of the root barrel `"."`, and types
 * an entry re-exports from another public entry (`OpenReason` in `select.json`).
 */
export interface ReexportedExport {
  name: string;
  kind: ApiExportKind;
  /** The import from THIS entry: `import { Alert } from '@nizivo/react'` in `index.json`. */
  import: string;
  /** The entry whose file documents it: `"./alert"`. */
  definedIn: string;
}

/** A prop, a render-state field, or an interface member. */
export interface MemberDoc {
  name: string;
  /**
   * The type as written in the public `.d.ts` (tsdown prints string literals in double quotes):
   * `"AlertTone"`, `"RenderProp<AlertState>"`. On an optional member a trailing `| undefined` is
   * dropped, because it only restates the `?` (`open?: boolean | undefined` → `"boolean"`). A method
   * member is written as a function type: `(delta: 1 | -1) => void`.
   */
  type: string;
  /**
   * Present when the type resolves to literal members only, after following aliases and dropping
   * `undefined`: `AlertTone` → `["info", "success", "warning", "critical"]`. The order is the one
   * written in the declaration that defines the union (the alias; the interface's members for
   * `keyof ButtonVariantMap`; the tuple for `(typeof SIDES)[number]`), never the checker's internal
   * union order, which is not stable. Absent for `boolean` alone.
   */
  values?: LiteralValue[];
  /** `false` when declared with `?`. */
  required: boolean;
  /**
   * The JSDoc `@default` text, verbatim (`"'info'"`, `"0"`). The tag is often written inline, after
   * the text of a one-line comment (`32 / 40 / 48 px. @default 'md'`), which TypeScript's JSDoc
   * parser reads as plain text, so the generator must find it there too and keep it out of
   * `description`.
   */
  default?: string;
  description?: string;
  deprecated?: Deprecation;
  /** For a member listed from a base interface declared in `@nizivo/react`: that base's name. */
  inheritedFrom?: string;
}

/** A base of a props interface that is summarised, not listed: React's DOM props. */
export interface InheritedProps {
  /** The base as written in the `extends` clause: `Omit<ComponentPropsWithRef<"div">, "title">`. */
  text: string;
  /** The base without `Omit` and `Partial`: `ComponentPropsWithRef<"div">`. */
  base: string;
  /** The intrinsic element of a `ComponentProps*` base (`"div"`), so docs can link its attributes. */
  element?: string;
  /** Keys removed with `Omit`, sorted. */
  omitted: string[];
  /** Own props that redeclare a name the base still provides (Alert's `role`), sorted. */
  overridden: string[];
}

/** The `render` prop (§10.1): its state argument `S` in `RenderProp<S>`. */
export interface RenderDoc {
  /** The state type (`"AlertState"`); absent when `S` is `Record<string, never>` (no state). */
  stateType?: string;
  /** The fields of `S`, sorted by `name`; empty when there is no state. */
  state: MemberDoc[];
}

/**
 * An element rendered with a `data-slot` (§8.2). A slot is API for CSS (its class is
 * `nz-<slot>`); it takes `render` only when `part` is `true`.
 */
export interface SlotInfo {
  /** The `data-slot` value: `"alert-title"`. */
  slot: string;
  /** The export or part that renders it: `"Alert"`, `"AlertDismiss"`, `"Card.Root"`. */
  renderedBy: string;
  /**
   * `true` for the root element of an export or part (its {@link ComponentDoc.slot}); `false` for
   * an inner element that CSS can target but that takes no `render` (`alert-title`, `kbd-glyphs`,
   * §8.2). Whether a root takes `render` is its component's `render` field: `Select.Root` and the
   * engine-owned popups (`select-popup`, `dialog-popup`, `tooltip-popup`) are roots without one.
   */
  part: boolean;
  /** Listed in the manifest's `interactive`: it gets the nz.base focus outline (§8.5). */
  interactive: boolean;
  /** For an interactive slot: the manifest's `focusTarget` mode for it. */
  focusTarget?: 'self' | 'nested-input' | 'within';
  /**
   * The manifest's `stateIndicator` entries for this slot (§8.5, §15.1): what `nz.base` paints on
   * it in forced-colours mode, in manifest order. Empty for most slots.
   */
  stateIndicator: StateIndicatorDoc[];
  /** The `data-*` attributes this element can carry, `data-slot` excluded, sorted by `name`. */
  attributes: DataAttributeDoc[];
}

/**
 * One forced-colours rule, `.nz-<slot><state> { <paint> }` inside `@media (forced-colors: active)`
 * in `@layer nz.base` (`packages/tooling/gen/COMPONENT-JSON.md`, "stateIndicator").
 */
export interface StateIndicatorDoc {
  /** The selector suffix it applies under (`[data-selected]`, `::-moz-meter-bar`); absent at rest. */
  state?: string;
  /** Which declarations it paints; COMPONENT-JSON.md lists each one's. */
  paint: 'border' | 'fill' | 'highlight' | 'mark' | 'outline';
}

/** A `data-*` or `data-nz-*` attribute, described by `contracts/vocabulary.json` (§8.3). */
export interface DataAttributeDoc {
  /** `"data-tone"`, `"data-open"`, `"data-nz-scheme"`. */
  name: string;
  /** The vocabulary group that lists it. */
  group: 'state' | 'presentational' | 'local' | 'scope';
  /** Present and `true` for a presence attribute (`data-open=""`), which has no `values`. */
  presence?: true;
  /**
   * The allowed values: the vocabulary's list, or, for an entry with `"values": null`, this
   * component's manifest `variants` under the camelCase prop name (§8.3 rule 5); in that order.
   */
  values?: string[];
  /**
   * The prop it mirrors: present when the rendering component's props type (DOM props included)
   * has a property named after the attribute in camelCase (`data-tone` ← `tone`, `data-full-width`
   * ← `fullWidth`, Button's `data-disabled` ← `disabled`). `data-span-sm` has none: GridItem's
   * `span` prop sets it through its `sm` key, and the vocabulary's `meaning` says so. Absent too
   * when both list literal values and the attribute has one the prop does not take: `data-side` on
   * Select.Popup and Tooltip.Popup is the resolved physical side, and `side` takes logical values.
   */
  prop?: string;
  /** The vocabulary's `meaning`. */
  meaning: string;
}

// ── contracts/api/css/<name>.json ──────────────────────────────────────────────────────────────

export interface CssApiFile {
  $comment: GeneratedComment;
  version: ApiFormatVersion;
  package: '@nizivo/react';
  /** The exports-map key: `"./css/alert.css"`. */
  entry: string;
  /** The component it styles (manifest `name`); absent for a shared file such as `base.css`. */
  component?: string;
  /**
   * The layers the file writes into, in file order: `["nz.components"]`; `base.css` writes
   * `["nz.base", "nz.utilities"]` (§8.1). The canonical layer statement on line 1 is not counted.
   */
  layers: string[];
  /** The public hooks the file reads (§8.4), sorted by `name`. */
  hooks: CssHookDoc[];
  /**
   * Every `--nz-*` token name the file reads anywhere (property values, private declarations,
   * fallbacks), sorted and unique. Hooks, `--_nz-*` privates and runtime variables are not tokens.
   * Their types live in `@nizivo/tokens/contract.json`.
   */
  tokens: string[];
  /** The runtime variables the file reads (`--nz-trigger-width`, §8.3), sorted. */
  runtime: string[];
  /** Every `nz-*` class the file selects, sorted (class names are semver'd, §5.4). */
  classes: string[];
}

/** A public hook, `--nz-<component>-<property>[-<state>]`, read and never assigned (§8.2, §8.4). */
export interface CssHookDoc {
  name: string;
  /**
   * The text of a `/** … *\/` doc comment written directly above the first declaration that reads
   * the hook in the source stylesheet (`src/<name>/<name>.css`), without the comment markers;
   * absent when there is none. A plain `/* … *\/` comment is a maintainer's note and is never
   * published (the JSDoc convention). Lightning CSS drops comments, so this comes from the source.
   */
  description?: string;
  /**
   * What applies when the consumer leaves the hook unset. Every read of a hook must have the same
   * fallback; the generator fails when two reads differ.
   */
  fallback: CssFallback;
  /** Every declaration that reads the hook, sorted by `selector`, then `property`. */
  reads: CssHookRead[];
}

export type CssFallback =
  /** `var(--nz-space-3)`: a token. */
  | { kind: 'token'; name: string }
  /** `var(--_nz-alert-bg)`: a private, whose declarations give the defaults per variant. */
  | { kind: 'private'; name: string; values: PrivateValue[] }
  /** `var(--nz-old-name, …)`: a deprecated hook kept as an alias for one minor (§8.4 rule 4). */
  | { kind: 'hook'; name: string }
  /** `8.75rem`, `cover`, `1em`: a plain value. */
  | { kind: 'literal'; value: string }
  /** Anything else (`calc(…)` over tokens), printed by Lightning CSS, with the tokens it reads. */
  | { kind: 'expression'; value: string; tokens: string[] };

/**
 * One declaration of a private variable (§8.2: set only by variant, size and tone rules); a rule
 * with a selector list gives one per selector, each with its own `when`.
 */
export interface PrivateValue {
  /** As in {@link CssHookRead.selector}. */
  selector: string;
  conditions: string[];
  /** The declared value as Lightning CSS prints it: `var(--nz-bg-info-subtle)`. */
  value: string;
  /**
   * The `data-*` attribute conditions on the selector's subject, as attribute name → value (`""`
   * for a presence attribute): `{ "data-tone": "critical" }`. Empty for the rest rule.
   */
  when: Record<string, string>;
}

export interface CssHookRead {
  /**
   * The rule's selector with nesting resolved, as Lightning CSS prints it unminified (attribute
   * values in double quotes): `.nz-alert-dismiss:hover`. Lightning CSS's `transform` with targets
   * below native nesting (for example `{ chrome: 100 << 16 }`) and `minify: false` prints exactly
   * this form. A rule with a selector list gives one read per selector, so `slot` is exact.
   */
  selector: string;
  /** The enclosing conditional at-rules, outermost first, layers excluded: `["@media (hover: hover)"]`. */
  conditions: string[];
  /** The property that reads it: `color`, `padding-block`. */
  property: string;
  /**
   * The `data-slot` of the element that reads it: the last `nz-*` class of the selector's subject
   * compound, minus `nz-` (`.nz-alert-dismiss:hover` → `alert-dismiss`).
   */
  slot: string;
}
