// Measures every size entry and, with --write, records the result (ARCHITECTURE.md §17).
//
//   node packages/tooling/size/measure.ts            print measured vs recorded vs limit
//   node packages/tooling/size/measure.ts --write    record `measured` for every entry, a limit for
//                                                    entries that have none, and SIZES.md's tables
//   node packages/tooling/size/measure.ts --write --rebase
//                                                    also reset every limit to measured + 10%
// A limit never exceeds the entry's §17.1 plan limit (method.ts PLAN_LIMITS_KIB).
//
// Run after `pnpm build`. The gate is `pnpm --filter @nizivo/react size`, which reads budgets.json.
// --write never raises an existing limit: that is --rebase, in a labelled PR (§17.3).
import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { parseArgs } from 'node:util';
import { BUDGETS, sizeEntries, type Budget, type Family, type SizeEntry } from './checks.ts';
import {
  kib,
  limitBytes,
  limitKiB,
  PLAN_LIMITS_KIB,
  REACT_DIR,
  REPO_ROOT,
  SIZE_DIR,
} from './method.ts';

const SIZE_LIMIT = join(REACT_DIR, 'node_modules', 'size-limit', 'bin.js');
const SIZES_MD = join(REACT_DIR, 'SIZES.md');
const BUDGETS_JSON = join(SIZE_DIR, 'budgets.json');

interface Result {
  name: string;
  size: number;
}

function isResults(value: unknown): value is Result[] {
  return (
    Array.isArray(value) &&
    value.every(
      (item: unknown) =>
        typeof item === 'object' &&
        item !== null &&
        'name' in item &&
        typeof item.name === 'string' &&
        'size' in item &&
        typeof item.size === 'number',
    )
  );
}

/** Runs size-limit in packages/react with the given mode and returns size by check name. */
export function runSizeLimit(mode: 'measure' | 'brotli'): Map<string, number> {
  const run = spawnSync(process.execPath, [SIZE_LIMIT, '--json'], {
    cwd: REACT_DIR,
    env: { ...process.env, NZ_SIZE_MODE: mode },
    encoding: 'utf8',
    maxBuffer: 64 * 1024 * 1024,
  });
  let parsed: unknown;
  try {
    parsed = JSON.parse(run.stdout);
  } catch {
    throw new Error(`size-limit printed no JSON (exit ${run.status}):\n${run.stdout}${run.stderr}`);
  }
  if (!isResults(parsed)) throw new Error(`size-limit failed:\n${JSON.stringify(parsed, null, 2)}`);
  return new Map(parsed.map((r) => [r.name, r.size]));
}

const FAMILY_TITLES: Record<Family, string> = {
  entry: 'Public JS entries (bundled with what they import, React Aria included)',
  composite: 'Composite bundles (one bundle; React Aria counted once)',
  own: 'Own code (one module minified alone, imports not counted)',
  seam: 'Seam helpers (seam ledger K6 and K7; React Aria external)',
  file: 'CSS and JSON entries (the published file, gzip)',
};
const FAMILIES: Family[] = ['entry', 'composite', 'own', 'seam', 'file'];

function cell(n: number): string {
  return n.toLocaleString('en-US');
}

/** The generated tables of SIZES.md: one per package and family. */
export function tables(
  entries: readonly SizeEntry[],
  budgets: Readonly<Record<string, Budget>>,
  brotli: ReadonlyMap<string, number>,
): string {
  const out: string[] = [];
  for (const pkg of ['react', 'tokens', 'icons'] as const) {
    for (const family of FAMILIES) {
      const rows = entries.filter((e) => e.pkg === pkg && e.family === family);
      if (rows.length === 0) continue;
      out.push(`#### \`@nizivo/${pkg}\`: ${FAMILY_TITLES[family]}`, '');
      out.push('| Entry | gzip (B) | gzip (KiB) | brotli (B) | Limit (KiB) | Headroom (B) |');
      out.push('| --- | ---: | ---: | ---: | ---: | ---: |');
      for (const e of rows) {
        const budget = budgets[e.name];
        if (budget === undefined) continue;
        const limit = limitBytes(budget.limitKiB);
        const headroom = limit === 0 ? '—' : cell(limit - budget.measured);
        const br = brotli.get(e.name);
        out.push(
          `| ${e.name.replace(`@nizivo/${pkg}`, '') || '`.`'} | ${cell(budget.measured)} | ${kib(budget.measured)} | ${br === undefined ? '—' : cell(Math.max(0, br))} | ${budget.limitKiB} | ${headroom} |`,
        );
      }
      out.push('');
    }
  }
  return out.join('\n').trimEnd();
}

const START = '<!-- size:tables:start (generated by packages/tooling/size/measure.ts --write) -->';
const END = '<!-- size:tables:end -->';

/** Replaces the text between `start` and `end` in `file`. */
export function replaceBlock(file: string, start: string, end: string, body: string): void {
  const text = readFileSync(file, 'utf8');
  const from = text.indexOf(start);
  const to = text.indexOf(end);
  if (from === -1 || to === -1 || to < from)
    throw new Error(`${file}: markers ${start} … ${end} not found`);
  writeFileSync(file, `${text.slice(0, from + start.length)}\n\n${body}\n\n${text.slice(to)}`);
}

/** Formats a written Markdown file the way `pnpm lint` (oxfmt --check) expects. */
export function formatMarkdown(file: string): void {
  const oxfmt = join(REPO_ROOT, 'node_modules', '.bin', 'oxfmt');
  const run = spawnSync(oxfmt, [file], { cwd: REPO_ROOT, encoding: 'utf8' });
  if (run.status !== 0) throw new Error(`oxfmt failed on ${file}:\n${run.stdout}${run.stderr}`);
}

function main(): void {
  const { values } = parseArgs({
    options: { write: { type: 'boolean' }, rebase: { type: 'boolean' } },
  });
  const entries = sizeEntries();
  const gzip = runSizeLimit('measure');
  const brotli = runSizeLimit('brotli');
  const next: Record<string, Budget> = {};
  let raised = 0;
  for (const e of entries) {
    const size = gzip.get(e.name);
    if (size === undefined) throw new Error(`size-limit reported no size for ${e.name}`);
    // size-limit subtracts an empty bundle's bytes, so an empty module reads below 0.
    const measured = Math.max(0, size);
    const recorded = BUDGETS[e.name];
    const plan = PLAN_LIMITS_KIB[e.name];
    const base =
      recorded === undefined || values.rebase === true ? limitKiB(measured) : recorded.limitKiB;
    // never above the plan's §17.1 limit, a recorded budget included
    const limit = plan === undefined ? base : Math.min(base, plan);
    if (recorded !== undefined && limit > recorded.limitKiB) raised += 1;
    next[e.name] = { measured, limitKiB: limit };
    const over = measured > limitBytes(limit) ? '  OVER' : '';
    console.log(
      `${e.name.padEnd(72)} ${String(measured).padStart(7)} B  recorded ${String(recorded?.measured ?? '—').padStart(7)}  limit ${limit} KiB${over}`,
    );
  }
  if (values.write !== true) return;
  const json: unknown = JSON.parse(readFileSync(BUDGETS_JSON, 'utf8'));
  const comment =
    typeof json === 'object' && json !== null && '$comment' in json ? json.$comment : '';
  writeFileSync(BUDGETS_JSON, `${JSON.stringify({ $comment: comment, entries: next }, null, 2)}\n`);
  replaceBlock(SIZES_MD, START, END, tables(entries, next, brotli));
  formatMarkdown(SIZES_MD);
  console.log(
    `\nWrote ${BUDGETS_JSON} and the tables in ${SIZES_MD}` +
      (raised > 0 ? ` (${raised} limits raised by --rebase: a labelled PR, §17.3)` : ''),
  );
}

if (import.meta.main) main();
