import {
  cpSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  renameSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { afterEach, describe, expect, test } from 'vitest';
import { generate } from '../gen/generate.ts';

const fixture = fileURLToPath(new URL('fixtures/repo', import.meta.url));
const roots: string[] = [];

/** A writable copy of the fixture repo; generation never runs on the fixture itself. */
function copyFixture(): string {
  const root = mkdtempSync(join(tmpdir(), 'nz-gen-'));
  cpSync(fixture, root, { recursive: true });
  roots.push(root);
  return root;
}

afterEach(() => {
  for (const root of roots.splice(0)) rmSync(root, { recursive: true, force: true });
});

const react = (root: string, path: string) => join(root, 'packages', 'react', path);
const read = (file: string) => readFileSync(file, 'utf8');
const edit = (file: string, change: (text: string) => string) =>
  writeFileSync(file, change(read(file)));

/** Generated files as { 'repo/relative/path': content }, for snapshots and lookups. */
function run(root: string): Record<string, string | null> {
  const { files, errors } = generate(root);
  expect(errors).toEqual([]);
  return Object.fromEntries(
    [...files].map(([file, content]) => [relative(root, file).split(sep).join('/'), content]),
  );
}

function errorsOf(root: string): string[] {
  return generate(root).errors;
}

describe('nz gen on the fixture components', () => {
  test('generates the expected files', () => {
    const files = run(copyFixture());
    expect(Object.keys(files).toSorted()).toEqual([
      'design/component-map.json',
      'packages/react/package.json',
      'packages/react/src/button/index.ts',
      'packages/react/src/index.ts',
      'packages/react/src/select/engine.ts',
      'packages/react/src/select/index.ts',
      'packages/react/src/select/select.parts.ts',
    ]);
    for (const [path, content] of Object.entries(files)) expect(content).toMatchSnapshot(path);
  });

  test('is deterministic', () => {
    expect(run(copyFixture())).toEqual(run(copyFixture()));
  });

  test('every generated TypeScript file starts with the header and carries no directive', () => {
    const files = run(copyFixture());
    for (const [path, content] of Object.entries(files)) {
      if (!path.endsWith('.ts')) continue;
      expect(content?.split('\n')[0]).toBe('// generated by nz gen; do not edit');
      expect(content).not.toMatch(/['"]use (client|server)['"]/);
    }
  });

  test('never re-exports examples, internals or the engine interface', () => {
    const files = run(copyFixture());
    const all = Object.values(files).join('\n');
    expect(all).not.toContain('ButtonExample');
    expect(all).not.toContain('scope');
    expect(all).not.toContain('SelectEngine');
  });
});

describe('validation', () => {
  test('reports a part the client leaf does not export', () => {
    const root = copyFixture();
    edit(react(root, 'src/select/select.client.tsx'), (text) =>
      text.replace('export const SelectSeparator', 'const SelectSeparator'),
    );
    expect(errorsOf(root)).toEqual([
      expect.stringContaining(
        '"SelectSeparator" is not exported by any module in packages/react/src/select',
      ),
    ]);
  });

  test('reports a name exported by two modules', () => {
    const root = copyFixture();
    writeFileSync(react(root, 'src/button/button-copy.tsx'), 'export const Button = 1;\n');
    expect(errorsOf(root)).toEqual([
      expect.stringContaining('"Button" is exported by more than one module'),
    ]);
  });

  test('reports an engine adapter that misses a member of the engine interface', () => {
    const root = copyFixture();
    edit(react(root, 'src/_engines/react-aria/select.client.tsx'), (text) =>
      text.replace('export const GroupLabel', 'const GroupLabel'),
    );
    expect(errorsOf(root)).toEqual([
      expect.stringContaining(
        'must export every SelectEngine member for engine.ts; missing GroupLabel',
      ),
    ]);
  });

  test("keeps a client part out of a server component's namespace", () => {
    const root = copyFixture();
    edit(react(root, 'src/button/component.json'), (text) =>
      text.replace('"tier": "server",', '"tier": "server",\n  "parts": ["Root", "Spinner"],'),
    );
    writeFileSync(
      react(root, 'src/button/button-root.tsx'),
      'export function ButtonRoot(): null {\n  return null;\n}\n',
    );
    writeFileSync(
      react(root, 'src/button/button-spinner.client.tsx'),
      "'use client';\nexport function ButtonSpinner(): null {\n  return null;\n}\n",
    );
    expect(errorsOf(root)).toEqual([
      expect.stringContaining(
        'a server component\'s namespace cannot hold a client part (Spinner): list ButtonSpinner in "exports" instead',
      ),
    ]);
  });

  test('checks a second adapter like the default one, and keeps engine.ts on the default', () => {
    const root = copyFixture();
    edit(react(root, 'src/select/component.json'), (text) =>
      text.replace('"engine": "react-aria",', '"engine": "react-aria",\n  "adapter": "hooks",'),
    );
    expect(errorsOf(root)).toEqual([
      expect.stringContaining(
        '"adapter": "hooks" names a missing file: packages/react/src/_engines/react-aria/select.hooks.client.tsx',
      ),
    ]);
    const second = react(root, 'src/_engines/react-aria/select.hooks.client.tsx');
    writeFileSync(
      second,
      readFileSync(react(root, 'src/_engines/react-aria/select.client.tsx'), 'utf8').replace(
        'export const GroupLabel',
        'const GroupLabel',
      ),
    );
    expect(errorsOf(root)).toEqual([
      expect.stringContaining(
        'select.hooks.client.tsx must export every SelectEngine member, as the default adapter does; missing GroupLabel',
      ),
    ]);
    edit(second, (text) => text.replace('const GroupLabel', 'export const GroupLabel'));
    expect(run(root)['packages/react/src/select/engine.ts']).toContain(
      "from '../_engines/react-aria/select.client'",
    );
  });

  test('takes engine.ts names from the engine interface, so a leaf-only part needs no adapter export', () => {
    const root = copyFixture();
    edit(react(root, 'src/select/component.json'), (text) =>
      text.replace('"Separator"]', '"Separator", "Footer"]'),
    );
    edit(
      react(root, 'src/select/select.client.tsx'),
      (text) => `${text}\nexport function SelectFooter(): null {\n  return null;\n}\n`,
    );
    const files = run(root);
    expect(files['packages/react/src/select/engine.ts']).not.toContain('Footer');
    expect(files['packages/react/src/select/select.parts.ts']).toContain('SelectFooter as Footer');
  });

  test('requires engine-tier components to declare the engine interface in their contract', () => {
    const root = copyFixture();
    edit(react(root, 'src/select/select.contract.ts'), (text) =>
      text.replace('export interface SelectEngine', 'interface SelectEngine'),
    );
    expect(errorsOf(root)).toEqual([
      expect.stringContaining(
        'engine-tier components declare their seam as an exported "interface SelectEngine"',
      ),
    ]);
  });

  test('requires overlay components to use the overlay family engine from engines.json', () => {
    const root = copyFixture();
    writeFileSync(react(root, 'engines.json'), '{ "overlay": "base-ui" }\n');
    expect(errorsOf(root)).toEqual([
      expect.stringContaining(
        'must use the overlay family engine from packages/react/engines.json ("base-ui")',
      ),
    ]);
  });

  test('rejects unknown keys, a bad tier and a name that does not match the folder', () => {
    const root = copyFixture();
    edit(react(root, 'src/button/component.json'), (text) =>
      text
        .replace('"name": "button"', '"name": "btn", "parst": []')
        .replace('"server"', '"static"'),
    );
    expect(errorsOf(root)).toEqual([
      'packages/react/src/button/component.json: unknown key "parst" (allowed: name, status, tier, engine, overlay, adapter, parts, exports, interactive, focusTarget, stateIndicator, cssDeps, variants, figma, budget)',
      'packages/react/src/button/component.json: "name" is "btn" but the folder is "button"; they must match',
      'packages/react/src/button/component.json: "tier" must be one of server, client, engine, own',
    ]);
  });

  test('ties "engine" to tier "engine" and "status" to the folder', () => {
    const root = copyFixture();
    edit(react(root, 'src/button/component.json'), (text) =>
      text.replace('"status": "stable"', '"status": "unstable", "engine": "react-aria"'),
    );
    expect(errorsOf(root)).toEqual([
      'packages/react/src/button/component.json: "status" is "unstable" but the component is not under src/unstable/',
      'packages/react/src/button/component.json: "engine" is only allowed when "tier" is "engine" or "own"',
    ]);
  });

  test('checks an "own" component\'s engine seam as an engine-tier one, without parts', () => {
    const root = copyFixture();
    edit(react(root, 'src/button/component.json'), (text) =>
      text.replace('"tier": "server"', '"tier": "own", "engine": "react-aria"'),
    );
    expect(errorsOf(root)).toEqual([
      'packages/react/src/button/component.json: engine-tier components declare their seam as an exported "interface ButtonEngine" with at least one member in packages/react/src/button/button.contract.ts',
      'packages/react/src/button/component.json: engine adapter not found: packages/react/src/_engines/react-aria/button.client.tsx',
    ]);
  });

  test('keeps the namespace name out of a compound component\'s "exports"', () => {
    const root = copyFixture();
    edit(react(root, 'src/select/component.json'), (text) =>
      text.replace('"overlay": true,', '"overlay": true,\n  "exports": ["Select"],'),
    );
    writeFileSync(react(root, 'src/select/select-flat.tsx'), 'export const Select = 1;\n');
    expect(errorsOf(root)).toEqual([
      'packages/react/src/select/component.json: "exports" cannot list "Select": it is the namespace of this compound component',
    ]);
  });

  test('reports invalid JSON with the file name', () => {
    const root = copyFixture();
    writeFileSync(react(root, 'src/button/component.json'), '{ "name": ');
    expect(errorsOf(root)).toEqual([
      expect.stringMatching(/^packages\/react\/src\/button\/component\.json: invalid JSON/),
    ]);
  });

  test('writes nothing when anything is invalid', () => {
    const root = copyFixture();
    edit(react(root, 'src/button/component.json'), (text) => text.replace('"server"', '"static"'));
    expect(generate(root).files.size).toBe(0);
  });
});

describe('root barrel', () => {
  test('shares one binding exported by two components, and rejects two different ones', () => {
    const root = copyFixture();
    cpSync(react(root, 'src/button'), react(root, 'src/link'), { recursive: true });
    rmSync(react(root, 'src/link/button.example.tsx'));
    writeFileSync(react(root, 'src/link/component.json'), '{ "name": "link", "tier": "server" }\n');
    // Same binding: Link re-exports Select's OpenReason, so the root entry exports it once.
    writeFileSync(
      react(root, 'src/link/button.tsx'),
      "export type { OpenReason } from '../select/select.contract';\nexport function Link(): null {\n  return null;\n}\n",
    );
    const barrel = run(root)['packages/react/src/index.ts'];
    expect(barrel).toContain("export type { OpenReason } from './link/index';");
    expect(barrel).not.toMatch(/OpenReason,[^;]*from '.\/select\/index'/);

    // A different declaration with the same name is an error.
    writeFileSync(
      react(root, 'src/link/button.tsx'),
      "export type OpenReason = 'press';\nexport function Link(): null {\n  return null;\n}\n",
    );
    expect(errorsOf(root)).toEqual([
      'root barrel: "OpenReason" is exported by both link and select; names in the root entry must be unique, so rename one',
    ]);
  });

  test('stays a valid module with no stable components', () => {
    const root = copyFixture();
    rmSync(react(root, 'src/button'), { recursive: true });
    rmSync(react(root, 'src/select'), { recursive: true });
    expect(run(root)['packages/react/src/index.ts']).toBe(
      '// generated by nz gen; do not edit\n' +
        '// oxlint-disable-next-line unicorn/require-module-specifiers -- no stable components yet\n' +
        'export {};\n',
    );
  });
});

describe('exports map', () => {
  test('drops a removed component and keeps hand-written entries whose source exists', () => {
    const root = copyFixture();
    rmSync(react(root, 'src/button'), { recursive: true });
    edit(react(root, 'package.json'), (text) => {
      const pkg = JSON.parse(text);
      pkg.exports['./button'] = {
        types: './dist/button/index.d.ts',
        default: './dist/button/index.js',
      };
      pkg.exports['./css/button.css'] = './dist/css/button.css';
      pkg.exports['./styles.css'] = './dist/styles.css';
      return JSON.stringify(pkg, null, 2);
    });
    const pkg = JSON.parse(run(root)['packages/react/package.json'] ?? '{}');
    expect(Object.keys(pkg.exports)).toEqual([
      '.',
      './config',
      './select',
      './css/base.css',
      './css/select.css',
      './styles.css',
      './package.json',
    ]);
  });

  test('puts an unstable component on ./unstable/<name>, outside the root barrel', () => {
    const root = copyFixture();
    renameSync(react(root, 'src/button'), react(root, 'src/unstable-tmp'));
    cpSync(react(root, 'src/unstable-tmp'), react(root, 'src/unstable/button'), {
      recursive: true,
    });
    rmSync(react(root, 'src/unstable-tmp'), { recursive: true });
    edit(react(root, 'src/unstable/button/component.json'), (text) =>
      text.replace('"stable"', '"unstable"'),
    );
    const files = run(root);
    const pkg = JSON.parse(files['packages/react/package.json'] ?? '{}');
    expect(pkg.exports['./unstable/button']).toEqual({
      types: './dist/unstable/button/index.d.ts',
      default: './dist/unstable/button/index.js',
    });
    expect(pkg.exports['./css/button.css']).toBe('./dist/css/button.css');
    expect(files['packages/react/src/index.ts']).not.toContain('Button');
    expect(files['design/component-map.json']).toContain(
      '"import": "@nizivo/react/unstable/button"',
    );
  });
});

describe('stale generated files', () => {
  test('are deleted when a component stops needing them', () => {
    const root = copyFixture();
    for (const [path, content] of Object.entries(run(root))) {
      mkdirSync(dirname(join(root, path)), { recursive: true });
      writeFileSync(join(root, path), content ?? '');
    }
    edit(react(root, 'src/select/component.json'), (text) =>
      text.replace(
        '"tier": "engine",\n  "engine": "react-aria",\n  "overlay": true,',
        '"tier": "client",',
      ),
    );
    const files = run(root);
    expect(files['packages/react/src/select/engine.ts']).toBeNull();
    expect(files['packages/react/src/select/select.parts.ts']).toEqual(expect.any(String));
  });

  test('are never deleted when they are hand-written', () => {
    const root = copyFixture();
    writeFileSync(react(root, 'src/button/engine.ts'), '// hand-written\nexport {};\n');
    expect(run(root)).not.toHaveProperty(['packages/react/src/button/engine.ts']);
  });
});

describe('families and extra exports', () => {
  test('"exports" names the values of a family subpath', () => {
    const root = copyFixture();
    edit(react(root, 'src/button/component.json'), (text) =>
      text.replace(
        '"tier": "server",',
        '"tier": "server",\n  "exports": ["Button", "ButtonGroup"],',
      ),
    );
    writeFileSync(
      react(root, 'src/button/button-group.tsx'),
      'export function ButtonGroup(): null {\n  return null;\n}\n',
    );
    expect(run(root)['packages/react/src/button/index.ts']).toBe(
      '// generated by nz gen; do not edit\n' +
        "export { Button } from './button';\n" +
        "export { ButtonGroup } from './button-group';\n" +
        "export type { ButtonProps, ButtonState, ButtonVariant } from './button';\n",
    );
  });
});
