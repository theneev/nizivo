// Reads the generated API records, contracts/api/react/<entry>.json and contracts/api/css/<name>.json
// (packages/tooling/api/schema.ts, API-JSON.md). Props, parts, data attribute and hook tables come
// from these files and nothing else (ARCHITECTURE.md §18.2). A missing or malformed file fails the
// build: an empty table would read as "this component has no props".
import type {
  ApiExport,
  ComponentExport,
  CssApiFile,
  NamespaceExport,
  ReactApiFile,
  ReexportedExport,
} from '@nizivo/tooling/api/schema';
import { existsSync, readFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { isRecord, parseJson } from '../scripts/json';
import type { CatalogEntry } from './catalog';
import { REPO_ROOT, repoPath } from './repo';

/** Where the API records live: the repo's `contracts/api`, written by `nz api` (§18.2). */
function apiDir(): string {
  return repoPath('contracts', 'api');
}

interface ApiHeader {
  $comment: string;
  version: number;
  package: string;
  entry: string;
}

function isReactApi(value: unknown): value is ReactApiFile {
  return isRecord(value) && Array.isArray(value.exports) && Array.isArray(value.slots);
}

function isCssApi(value: unknown): value is CssApiFile {
  return (
    isRecord(value) &&
    Array.isArray(value.hooks) &&
    Array.isArray(value.tokens) &&
    Array.isArray(value.layers)
  );
}

function readApi<T extends ApiHeader>(
  file: string,
  entry: string,
  guard: (value: unknown) => value is T,
): T {
  const shown = relative(REPO_ROOT, file);
  if (!existsSync(file)) {
    throw new Error(
      `docs: ${shown} is missing. Every public entry of @nizivo/react needs its API record; ` +
        'run `nz api` after `pnpm build` (ARCHITECTURE.md §18.2).',
    );
  }
  const data = parseJson(readFileSync(file, 'utf8'), guard, shown);
  if (data.$comment !== 'generated by nz api; do not edit' || data.version !== 1) {
    throw new Error(
      `docs: ${shown} is not a version 1 API record (packages/tooling/api/schema.ts).`,
    );
  }
  if (data.package !== '@nizivo/react' || data.entry !== entry) {
    throw new Error(`docs: ${shown} describes ${data.package} ${data.entry}, expected ${entry}.`);
  }
  return data;
}

const reactCache = new Map<string, ReactApiFile>();
const cssCache = new Map<string, CssApiFile>();

export function reactApi(entry: CatalogEntry): ReactApiFile {
  const hit = reactCache.get(entry.name);
  if (hit) return hit;
  const file = readApi(join(apiDir(), 'react', `${entry.name}.json`), entry.entry, isReactApi);
  if (entry.kind === 'component' && file.component === undefined) {
    throw new Error(
      `docs: react/${entry.name}.json has no component field, but component.json exists.`,
    );
  }
  reactCache.set(entry.name, file);
  return file;
}

/** The stylesheet record of an entry, or undefined when the exports map has no stylesheet for it. */
export function cssApi(entry: CatalogEntry): CssApiFile | undefined {
  if (entry.stylesheet === undefined) return undefined;
  const name = entry.stylesheet.replace(/^\.\/css\//, '').replace(/\.css$/, '');
  const hit = cssCache.get(name);
  if (hit) return hit;
  const file = readApi(join(apiDir(), 'css', `${name}.json`), entry.stylesheet, isCssApi);
  cssCache.set(name, file);
  return file;
}

export type OwnExport = Exclude<ApiExport, ReexportedExport>;

/** Narrows on `definedIn`, the one field only a re-export has (API-JSON.md). */
export function isOwn(e: ApiExport): e is OwnExport {
  return e.definedIn === undefined;
}

export function ownExports(file: ReactApiFile): OwnExport[] {
  return file.exports.filter(isOwn);
}

export function reexports(file: ReactApiFile): ReexportedExport[] {
  return file.exports.filter((e): e is ReexportedExport => e.definedIn !== undefined);
}

/** Standalone components and compound namespaces: what the Props and Parts sections render. */
export function documentedComponents(file: ReactApiFile): (ComponentExport | NamespaceExport)[] {
  return ownExports(file).filter(
    (e): e is ComponentExport | NamespaceExport => e.kind === 'component' || e.kind === 'namespace',
  );
}

/** The import lines a page shows: runtime exports first, then one `import type` line. */
export function importLines(file: ReactApiFile, specifier: string): string[] {
  const runtime = ownExports(file)
    .filter((e) => e.kind === 'component' || e.kind === 'namespace')
    .map((e) => e.name);
  const lines: string[] = [];
  if (runtime.length > 0) lines.push(`import { ${runtime.join(', ')} } from '${specifier}';`);
  return lines;
}
