// Reads the generated API records of @nizivo/charts: contracts/api/charts/<entry>.json and
// contracts/api/charts/css/<part>.json (packages/tooling/api/schema.ts, API-JSON.md "@nizivo/charts"),
// and the charts example manifest written by scripts/generate.ts. The charts pages' props, labels
// and hook tables come from these files, as react's do from contracts/api (ARCHITECTURE.md §18.2).
// A missing or malformed file fails the build: an empty table would read as "this part has no props".
import type {
  ApiExport,
  ChartsApiFile,
  CssApiFile,
  ReexportedExport,
} from '@nizivo/tooling/api/schema';
import type { ExampleEntry, ExampleManifest } from '../scripts/examples';
import { hasExports, isRecord } from '../scripts/json';
import { readRepoJson, readRepoText, repoFileExists } from './repo';

const PACKAGE = '@nizivo/charts';
const PRODUCED_BY = 'run `nz api` after `pnpm build` (ARCHITECTURE.md §18.2)';

export type OwnChartsExport = Exclude<ApiExport, ReexportedExport>;

interface Header {
  $comment: unknown;
  version: unknown;
  package: unknown;
  entry: unknown;
}

function isChartsApi(value: unknown): value is ChartsApiFile {
  return isRecord(value) && Array.isArray(value.exports) && typeof value.entry === 'string';
}

function isCssApi(value: unknown): value is CssApiFile {
  return (
    isRecord(value) &&
    Array.isArray(value.hooks) &&
    Array.isArray(value.tokens) &&
    Array.isArray(value.layers)
  );
}

function checkHeader(path: string, data: Header, entry: string): void {
  if (data.$comment !== 'generated by nz api; do not edit' || data.version !== 1) {
    throw new Error(
      `docs: ${path} is not a version 1 API record (packages/tooling/api/schema.ts).`,
    );
  }
  if (data.package !== PACKAGE || data.entry !== entry) {
    throw new Error(
      `docs: ${path} describes ${String(data.package)} ${String(data.entry)}, expected ${PACKAGE} ${entry}.`,
    );
  }
}

/** `.` → `index`, `./bar-chart` → `bar-chart`: the file name of an entry's record. */
function fileOf(entry: string): string {
  return entry === '.' ? 'index' : entry.replace(/^\.\//, '');
}

const apiCache = new Map<string, ChartsApiFile>();

/** The record of one entry of @nizivo/charts' exports map: `.` or `./bar-chart`. */
export function chartsApi(entry: string): ChartsApiFile {
  const hit = apiCache.get(entry);
  if (hit) return hit;
  const path = `contracts/api/charts/${fileOf(entry)}.json`;
  const data = readRepoJson(path, isChartsApi, PRODUCED_BY);
  checkHeader(path, data, entry);
  apiCache.set(entry, data);
  return data;
}

const cssCache = new Map<string, CssApiFile>();

/** The record of a part's sheet inside `@nizivo/charts/styles.css`. */
export function chartsCss(part: string): CssApiFile {
  const hit = cssCache.get(part);
  if (hit) return hit;
  const path = `contracts/api/charts/css/${part}.json`;
  const data = readRepoJson(path, isCssApi, PRODUCED_BY);
  checkHeader(path, data, './styles.css');
  if (data.component !== part) {
    throw new Error(
      `docs: ${path} describes the part ${String(data.component)}, expected ${part}.`,
    );
  }
  cssCache.set(part, data);
  return data;
}

function exportsMap(): Record<string, unknown> {
  return readRepoJson('packages/charts/package.json', hasExports).exports;
}

/**
 * The public entry a part is imported from today: its subpath once @nizivo/charts' exports map has
 * it, else the barrel while only the barrel re-exports it, else undefined (not public yet).
 */
export function chartsEntryKey(part: string): string | undefined {
  if (`./${part}` in exportsMap()) return `./${part}`;
  const barrel = readRepoText('packages/charts/src/index.ts');
  return barrel.includes(`export * from './${part}/index';`) ? '.' : undefined;
}

/** The import specifier of `chartsEntryKey`: `@nizivo/charts/bar-chart` or `@nizivo/charts`. */
export function chartsSpecifier(part: string): string | undefined {
  const key = chartsEntryKey(part);
  return key === undefined ? undefined : key === '.' ? PACKAGE : `${PACKAGE}/${key.slice(2)}`;
}

/** The record that documents a part: its subpath's, or the barrel's while it has no subpath. */
export function partApi(part: string): ChartsApiFile {
  const key = chartsEntryKey(part);
  if (key === undefined) {
    throw new Error(
      `docs: @nizivo/charts does not export '${part}' (no ./${part} subpath, not in the barrel).`,
    );
  }
  return chartsApi(key);
}

/** The exports a part's own source declares (`packages/charts/src/<part>/`), as documented. */
export function partExports(part: string): OwnChartsExport[] {
  const prefix = `packages/charts/src/${part}/`;
  return partApi(part).exports.filter(
    (e): e is OwnChartsExport =>
      e.definedIn === undefined &&
      (e.kind === 'namespace' || e.kind === 'part' ? false : e.source.startsWith(prefix)),
  );
}

/**
 * An export by name, documented where `definedIn` points (an entry key such as `./chart-frame`):
 * looked up in the part's record first, then the barrel's.
 */
export function findChartsExport(part: string, name: string): OwnChartsExport {
  const files = [partApi(part), chartsApi('.')];
  for (const file of files) {
    const found = file.exports.find((e) => e.name === name);
    if (found === undefined) continue;
    if (found.definedIn === undefined) return found;
    if (!found.definedIn.startsWith('.')) {
      throw new Error(
        `docs: ${name} is a type of ${found.definedIn}, which nz api does not describe.`,
      );
    }
    const home = chartsApi(found.definedIn).exports.find((e) => e.name === name);
    if (home !== undefined && home.definedIn === undefined) return home;
  }
  throw new Error(`docs: no contracts/api/charts record documents ${name} (part ${part}).`);
}

function isManifest(value: unknown): value is ExampleManifest {
  return (
    isRecord(value) && Object.values(value).every((f) => isRecord(f) && Array.isArray(f.examples))
  );
}

let manifestCache: ExampleManifest | undefined;

/** The charts snippets, from .generated/charts/manifest.json (scripts/examples.ts). */
export function chartsExample(part: string, name: string): ExampleEntry {
  manifestCache ??= readRepoJson(
    'apps/docs/.generated/charts/manifest.json',
    isManifest,
    'run `node scripts/generate.ts` in apps/docs (the docs build runs it first)',
  );
  const found = manifestCache[part]?.examples.find((e) => e.export === name);
  if (found === undefined) {
    throw new Error(
      `docs: packages/charts/src/${part}/${part}.example.tsx exports no example function ${name}.`,
    );
  }
  return found;
}

/** Whether a charts page has its own generated route (app/docs/(generated)/charts/<part>). */
export function hasChartsRoute(slugs: readonly string[]): boolean {
  if (slugs.length !== 2 || slugs[0] !== 'charts') return false;
  const path = 'apps/docs/.generated/charts/routes.json';
  if (!repoFileExists(path)) return false;
  const routes = readRepoJson(
    path,
    (v: unknown): v is string[] => Array.isArray(v) && v.every((x) => typeof x === 'string'),
  );
  return routes.includes(slugs[1] ?? '');
}
