// Copies every packages/react/src/<name>/<name>.example.tsx into .generated/examples/ with its
// relative imports rewritten to the public subpaths (`./index` → `@nizivo/react/<name>`,
// `../button/index` → `@nizivo/react/button`). The docs then render and show each example through
// the published API in dist, never the library source: two copies of a module would break React
// context identity and hide packaging bugs (ARCHITECTURE.md §18.2). Any import it cannot map fails
// the run. It also splits each file into one snippet per exported example (its imports and the
// local helpers it uses), which the component pages highlight with Shiki at build time.
//
// The same for @nizivo/charts (§14.1): packages/charts/src/<part>/<part>.example.tsx goes to
// .generated/charts/examples/, `./index` and `../<part>/index` mapped to the part's public entry
// (its subpath once the exports map has it, else the barrel `@nizivo/charts` while only the barrel
// re-exports it). Each charts snippet is also written as its own module under
// .generated/charts/snippets/<part>/, so the docs typecheck (`tsc -p .`, and `next build`) compiles
// every snippet a charts page shows, not only the whole example file (W10 R3-2: a snippet that left
// out a helper it used).
//
// And for the patterns (MIT, repo-root patterns/): patterns/src/<name>/<name>.example.tsx goes to
// .generated/patterns/ with its imports unchanged, because a pattern is app code and already imports
// the published entries (`@nizivo/react/<subpath>`, `@nizivo/charts[/<part>]`,
// `@nizivo/icons[/brands/<name>]`);
// any other import fails the run. Its snippets are written as modules too, as the charts ones are.
//
// scripts/generate.ts runs it before `fumadocs-mdx` and `next build`.
import { existsSync, readFileSync, readdirSync } from 'node:fs';
import { join, relative } from 'node:path';
import { hasExports, parseJson } from './json.ts';

const docsRoot = join(import.meta.dirname, '..');
const repoRoot = join(docsRoot, '..', '..');
const reactRoot = join(repoRoot, 'packages', 'react');
const chartsRoot = join(repoRoot, 'packages', 'charts');
const patternsRoot = join(repoRoot, 'patterns');
const HEADER = '// generated by apps/docs/scripts/examples.ts from packages/react; do not edit';
const CHARTS_HEADER =
  '// generated by apps/docs/scripts/examples.ts from packages/charts; do not edit';
const PATTERNS_HEADER = '// generated by apps/docs/scripts/examples.ts from patterns; do not edit';

/** Specifiers an example may import unchanged. */
const ALLOWED_EXTERNAL = new Set(['react', 'react-dom', 'react/jsx-runtime']);

export interface ExampleEntry {
  /** The exported function: `AlertDismissibleExample`. */
  export: string;
  /** `Dismissible`; `Basic` for the component's own `<Name>Example`. */
  title: string;
  /** The JSDoc above the function, without its markers. */
  description?: string;
  /** The snippet shown under the preview: the imports it uses, its helpers and the function. */
  code: string;
  /** `false` when the preview is not rendered, with `reason`. */
  live: boolean;
  reason?: string;
}

export interface ExampleFile {
  /** Repo-relative source: `packages/react/src/alert/alert.example.tsx`. */
  source: string;
  examples: ExampleEntry[];
}

export type ExampleManifest = Record<string, ExampleFile>;

interface ImportDecl {
  start: number;
  end: number;
  typeOnly: boolean;
  specifiers: { imported: string; local: string; typeOnly: boolean }[];
  /** Default or namespace import text, kept verbatim (`* as React`). */
  other?: string;
  from: string;
}

interface Block {
  /** First line of the block, its JSDoc included. */
  start: number;
  end: number;
  name: string;
  exported: boolean;
  doc?: string;
  /** The block without its JSDoc. */
  body: string;
  /** The block with its JSDoc. */
  text: string;
}

export class ExampleError extends Error {}

function fail(file: string, message: string): never {
  throw new ExampleError(`${relative(repoRoot, file)}: ${message}`);
}

function pascal(kebab: string): string {
  return kebab.replace(/(^|-)([a-z0-9])/g, (_m, _d: string, c: string) => c.toUpperCase());
}

/** The exports map of @nizivo/react. */
export function reactExports(): Record<string, unknown> {
  const file = join(reactRoot, 'package.json');
  return parseJson(readFileSync(file, 'utf8'), hasExports, relative(repoRoot, file)).exports;
}

/** JS subpaths of @nizivo/react, from its exports map: `alert`, `config`, … */
export function reactSubpaths(): string[] {
  return (
    Object.keys(reactExports())
      // files (./css/<name>.css, ./styles.css, ./package.json) are not JS subpaths
      .filter((k) => k.startsWith('./') && !/\.[a-z]+$/.test(k))
      .map((k) => k.slice(2))
      .toSorted()
  );
}

/** The exports map of @nizivo/charts. */
export function chartsExports(): Record<string, unknown> {
  const file = join(chartsRoot, 'package.json');
  return parseJson(readFileSync(file, 'utf8'), hasExports, relative(repoRoot, file)).exports;
}

/**
 * Where a charts part is imported from today: its own subpath once the exports map has it, else
 * the barrel when the barrel re-exports it (`export * from './<part>/index'`), else undefined (it is
 * not public).
 */
export function chartsEntryOf(part: string): string | undefined {
  if (`./${part}` in chartsExports()) return `@nizivo/charts/${part}`;
  const barrel = readFileSync(join(chartsRoot, 'src', 'index.ts'), 'utf8');
  return barrel.includes(`export * from './${part}/index';`) ? '@nizivo/charts' : undefined;
}

/** The charts parts with an example file, sorted: `area-chart`, `bar-chart`, … */
export function chartsExampleParts(): string[] {
  const src = join(chartsRoot, 'src');
  return readdirSync(src, { withFileTypes: true })
    .filter((d) => d.isDirectory() && existsSync(join(src, d.name, `${d.name}.example.tsx`)))
    .map((d) => d.name)
    .toSorted();
}

function mapChartsSpecifier(file: string, part: string, from: string): string {
  if (ALLOWED_EXTERNAL.has(from)) return from;
  const target = from === './index' ? part : /^\.\.\/([a-z0-9-]+)\/index$/.exec(from)?.[1];
  const entry = target === undefined ? undefined : chartsEntryOf(target);
  if (entry !== undefined) return entry;
  return fail(
    file,
    `cannot map the import '${from}' to a public entry of @nizivo/charts. An example may import ` +
      `its own part ('./index'), another public part ('../<part>/index') and react; a part is ` +
      'public once the exports map has its subpath or the barrel re-exports it.',
  );
}

function mapSpecifier(file: string, name: string, from: string, subpaths: Set<string>): string {
  if (ALLOWED_EXTERNAL.has(from)) return from;
  if (from === './index') return `@nizivo/react/${name}`;
  // an unstable component's example reaches the stable ones from src/unstable/<name>/
  const sibling = name.startsWith('unstable/')
    ? /^\.\.\/\.\.\/([a-z0-9-]+)\/index$/.exec(from)
    : /^\.\.\/([a-z0-9-]+)\/index$/.exec(from);
  if (sibling?.[1] !== undefined && subpaths.has(sibling[1])) return `@nizivo/react/${sibling[1]}`;
  // and another unstable part from ../<name>/ (AiWelcome's PromptComposer)
  const unstable = name.startsWith('unstable/') ? /^\.\.\/([a-z0-9-]+)\/index$/.exec(from) : null;
  if (unstable?.[1] !== undefined && subpaths.has(`unstable/${unstable[1]}`)) {
    return `@nizivo/react/unstable/${unstable[1]}`;
  }
  const pub = /^@nizivo\/react\/([a-z0-9-]+)$/.exec(from);
  if (pub?.[1] !== undefined && subpaths.has(pub[1])) return from;
  return fail(
    file,
    `cannot map the import '${from}' to a public entry of @nizivo/react. An example may import its ` +
      `own component ('./index'), another public component ('../<name>/index') and react.`,
  );
}

function parseImports(file: string, source: string): ImportDecl[] {
  const decls: ImportDecl[] = [];
  const re = /^import\s+(type\s+)?([\s\S]*?)\s+from\s+'([^']+)';[ \t]*$/gm;
  for (const m of source.matchAll(re)) {
    const clause = m[2] ?? '';
    const decl: ImportDecl = {
      start: m.index,
      end: m.index + m[0].length,
      typeOnly: m[1] !== undefined,
      specifiers: [],
      from: m[3] ?? '',
    };
    const braces = /\{([\s\S]*)\}/.exec(clause);
    const outside = clause
      .replace(/\{[\s\S]*\}/, '')
      .replace(/,\s*$/, '')
      .trim();
    if (outside) decl.other = outside.replace(/,$/, '').trim();
    for (const raw of (braces?.[1] ?? '').split(',')) {
      const s = raw.trim();
      if (!s) continue;
      const typeOnly = s.startsWith('type ');
      const [imported = '', local = imported] = s.replace(/^type\s+/, '').split(/\s+as\s+/);
      decl.specifiers.push({ imported, local, typeOnly });
    }
    decls.push(decl);
  }
  // Any other import form (side effects, CSS, dynamic import, require, re-exports) is refused.
  const stripped = decls.reduceRight(
    (text, d) => text.slice(0, d.start) + text.slice(d.end),
    source,
  );
  if (/^\s*import\s/m.test(stripped)) fail(file, 'an import statement has an unsupported form');
  if (/\bimport\(|\brequire\(|^export\s+\*|^export\s+\{[^}]*\}\s+from/m.test(stripped)) {
    fail(file, 'dynamic imports, require() and re-exports are not allowed in an example');
  }
  return decls;
}

/** Splits the formatted file (oxfmt) into its top-level declarations. */
function parseBlocks(file: string, source: string, imports: ImportDecl[]): Block[] {
  const lines = source.split('\n');
  const importLines = new Set<number>();
  for (const d of imports) {
    const first = source.slice(0, d.start).split('\n').length - 1;
    const last = source.slice(0, d.end).split('\n').length - 1;
    for (let i = first; i <= last; i++) importLines.add(i);
  }
  const blocks: Block[] = [];
  let i = 0;
  /** `//` lines right above a declaration (the charts examples explain their data so). */
  let comment: number | undefined;
  while (i < lines.length) {
    const line = lines[i] ?? '';
    if (importLines.has(i) || line.trim() === '') {
      comment = undefined;
      i++;
      continue;
    }
    if (line.startsWith('//')) {
      comment ??= i;
      i++;
      continue;
    }
    if (/^\s/.test(line)) fail(file, `line ${i + 1}: indented text outside a declaration`);
    const start = comment ?? i;
    comment = undefined;
    let doc: string | undefined;
    if (line.startsWith('/**')) {
      let j = i;
      while (j < lines.length && !(lines[j] ?? '').includes('*/')) j++;
      doc = lines
        .slice(i, j + 1)
        .join('\n')
        .replace(/^\/\*\*|\*\/$/g, '')
        .split('\n')
        .map((l) => l.replace(/^\s*\*\s?/, '').trim())
        .join(' ')
        .replace(/\s+/g, ' ')
        .trim();
      i = j + 1;
    }
    const head = lines[i] ?? '';
    const fn = /^(export\s+)?function\s+([A-Za-z0-9_]+)/.exec(head);
    const decl = /^(export\s+)?(?:const|let|type|interface)\s+([A-Za-z0-9_]+)/.exec(head);
    const m = fn ?? decl;
    if (!m) fail(file, `line ${i + 1}: unsupported top-level statement '${head}'`);
    let end = i;
    if (fn) {
      while (end < lines.length && lines[end] !== '}') end++;
    } else if (!head.trimEnd().endsWith(';')) {
      end = i + 1;
      while (end < lines.length && !/^[}\])]/.test(lines[end] ?? '')) end++;
    }
    if (end >= lines.length) fail(file, `line ${i + 1}: declaration does not end`);
    const body = lines.slice(i, end + 1).join('\n');
    blocks.push({
      start,
      end,
      name: m[2] ?? '',
      exported: m[1] !== undefined,
      ...(doc !== undefined && { doc }),
      body,
      text: lines.slice(start, end + 1).join('\n'),
    });
    i = end + 1;
  }
  return blocks;
}

/**
 * Whether `text` refers to `name`: not as a property (`x.name`) or part of a longer name. A spread
 * (`...name`) is a use, so its dots are blanked first.
 */
function uses(text: string, name: string): boolean {
  return new RegExp(`(?<![\\w.$])${name}(?![\\w$])`).test(text.replaceAll('...', '   '));
}

function printImport(typeOnly: boolean, names: string[], other: string | undefined, from: string) {
  const parts = [
    ...(other ? [other] : []),
    ...(names.length > 0 ? [`{ ${names.join(', ')} }`] : []),
  ];
  const one = `import ${typeOnly ? 'type ' : ''}${parts.join(', ')} from '${from}';`;
  if (one.length <= 100 || names.length === 0) return one;
  return `import ${typeOnly ? 'type ' : ''}${other ? `${other}, ` : ''}{\n${names
    .map((n) => `  ${n},`)
    .join('\n')}\n} from '${from}';`;
}

function snippet(example: Block, blocks: Block[], imports: ImportDecl[]): string {
  // Local helpers the example uses, followed transitively, in file order.
  const helpers = new Set<Block>();
  const queue = [example.body];
  while (queue.length > 0) {
    const text = queue.pop() ?? '';
    for (const b of blocks) {
      if (b === example || b.exported || helpers.has(b) || !uses(text, b.name)) continue;
      helpers.add(b);
      queue.push(b.body);
    }
  }
  const code = [...blocks.filter((b) => helpers.has(b)).map((b) => b.text), example.body];
  const body = code.join('\n\n');
  const importLines: string[] = [];
  for (const d of imports) {
    const names = d.specifiers
      .filter((s) => uses(body, s.local))
      .map(
        (s) =>
          `${s.typeOnly ? 'type ' : ''}${s.imported === s.local ? s.imported : `${s.imported} as ${s.local}`}`,
      );
    const other =
      d.other !== undefined && uses(body, d.other.replace(/^\*\s+as\s+/, '')) ? d.other : undefined;
    if (names.length === 0 && other === undefined) continue;
    importLines.push(printImport(d.typeOnly, names, other, d.from));
  }
  return `${importLines.join('\n')}\n\n${body}\n`;
}

function liveness(code: string): { live: boolean; reason?: string } {
  if (/\bdefaultOpen\b/.test(code)) {
    return {
      live: false,
      reason:
        'It opens on page load (`defaultOpen`), which would move focus on this page, so it is shown as source only.',
    };
  }
  if (/\btoast\(/.test(code)) {
    return {
      live: false,
      reason:
        'It shows toasts from an event handler or an effect, code that runs in a client component of your app, so it is shown as source only.',
    };
  }
  if (/\bon[A-Z]\w*=\{\s*\(/.test(code)) {
    return {
      live: false,
      reason:
        'It passes an event handler, code that runs in a client component of your app, so it is shown as source only.',
    };
  }
  const asset = /\bsrc=(?:"|\{\s*['"`])(\/[^"'`]*)/.exec(code);
  if (asset) {
    return {
      live: false,
      reason: `It loads ${asset[1]}, a file of your app that this site does not ship, so it is shown as source only.`,
    };
  }
  return { live: true };
}

export function generateExamples(): { files: Map<string, string>; manifest: ExampleManifest } {
  const subpathList = reactSubpaths();
  const subpaths = new Set(subpathList);
  const files = new Map<string, string>();
  const manifest: ExampleManifest = {};
  const srcRoot = join(reactRoot, 'src');

  // An example in a folder that is not a public entry would never appear in the docs.
  for (const dir of readdirSync(srcRoot, { withFileTypes: true })) {
    if (!dir.isDirectory()) continue;
    for (const f of readdirSync(join(srcRoot, dir.name))) {
      if (f.endsWith('.example.tsx') && !subpaths.has(dir.name)) {
        fail(join(srcRoot, dir.name, f), `'${dir.name}' is not a public entry of @nizivo/react`);
      }
      if (f.endsWith('.example.tsx') && f !== `${dir.name}.example.tsx`) {
        fail(join(srcRoot, dir.name, f), `expected the name ${dir.name}.example.tsx`);
      }
    }
  }

  for (const subpath of subpathList) {
    // ./unstable/<name> keeps its folder under src/unstable; its page and files use the bare name
    const name = subpath.replace(/^unstable\//, '');
    const file = join(srcRoot, subpath, `${name}.example.tsx`);
    if (!existsSync(file)) continue;
    const { module, entry } = exampleFile(file, name, HEADER, (from) =>
      mapSpecifier(file, subpath, from, subpaths),
    );
    files.set(`${name}.example.tsx`, module);
    manifest[name] = entry;
  }

  // No index module: each component route imports its own example file (scripts/generate.ts).
  files.set('manifest.json', `${JSON.stringify(manifest, null, 2)}\n`);
  return { files, manifest };
}

/**
 * One example file: the whole module with its imports rewritten by `map` (what a route imports
 * and renders), and its manifest entry (one snippet per exported example).
 */
function exampleFile(
  file: string,
  name: string,
  header: string,
  map: (from: string) => string,
): { module: string; entry: ExampleFile } {
  const source = readFileSync(file, 'utf8');
  const imports = parseImports(file, source);
  const rewritten = imports.map((d) => ({ ...d, from: map(d.from) }));
  // The whole file, imports rewritten in place: what the page imports and renders.
  let out = source;
  for (const d of [...rewritten].toReversed()) {
    const original = source.slice(d.start, d.end);
    const replaced = original.replace(/from\s+'[^']+';[ \t]*$/, `from '${d.from}';`);
    out = out.slice(0, d.start) + replaced + out.slice(d.end);
  }
  if (out.includes("from './") || out.includes("from '../")) {
    fail(file, 'a relative import survived the rewrite');
  }

  const blocks = parseBlocks(file, source, imports);
  const component = pascal(name);
  const examples: ExampleEntry[] = [];
  for (const b of blocks.filter((x) => x.exported)) {
    const code = snippet(b, blocks, rewritten);
    const stem = b.name.replace(/Example$/, '');
    const title =
      stem === component
        ? 'Basic'
        : stem.startsWith(component)
          ? stem.slice(component.length)
          : stem;
    examples.push({
      export: b.name,
      title: title.replace(/([a-z])([A-Z])/g, '$1 $2'),
      ...(b.doc !== undefined && { description: b.doc }),
      code,
      ...liveness(code),
    });
  }
  if (examples.length === 0) fail(file, 'exports no example function');
  return { module: `${header}\n${out}`, entry: { source: relative(repoRoot, file), examples } };
}

/**
 * The @nizivo/charts examples: `examples/<part>.example.tsx` (the module a charts route imports),
 * `snippets/<part>/<Export>.tsx` (each snippet on its own, for the typecheck) and `manifest.json`,
 * all relative to .generated/charts/. Every part with an example file must be public.
 */
export function generateChartsExamples(): {
  files: Map<string, string>;
  manifest: ExampleManifest;
} {
  const files = new Map<string, string>();
  const manifest: ExampleManifest = {};
  for (const part of chartsExampleParts()) {
    const file = join(chartsRoot, 'src', part, `${part}.example.tsx`);
    if (chartsEntryOf(part) === undefined) {
      fail(
        file,
        `'${part}' is not a public entry of @nizivo/charts (no subpath, not in the barrel)`,
      );
    }
    const { module, entry } = exampleFile(file, part, CHARTS_HEADER, (from) =>
      mapChartsSpecifier(file, part, from),
    );
    files.set(`examples/${part}.example.tsx`, module);
    for (const e of entry.examples) {
      files.set(`snippets/${part}/${e.export}.tsx`, `${CHARTS_HEADER}\n${e.code}`);
    }
    manifest[part] = entry;
  }
  files.set('manifest.json', `${JSON.stringify(manifest, null, 2)}\n`);
  return { files, manifest };
}

/** The patterns, sorted: every folder of patterns/src/ (each must hold `<name>.example.tsx`). */
export function patternNames(): string[] {
  const src = join(patternsRoot, 'src');
  if (!existsSync(src)) return [];
  return readdirSync(src, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => d.name)
    .toSorted();
}

/** The stylesheet of a pattern, repo-relative, or undefined when it has none. */
export function patternStylesheet(name: string): string | undefined {
  const file = join(patternsRoot, 'src', name, `${name}.css`);
  return existsSync(file) ? relative(repoRoot, file) : undefined;
}

function checkPatternSpecifier(
  file: string,
  from: string,
  reactPaths: Set<string>,
  chartsPaths: Set<string>,
): string {
  if (ALLOWED_EXTERNAL.has(from) || /^@nizivo\/icons(\/brands\/[a-z0-9-]+)?$/.test(from)) {
    return from;
  }
  const react = /^@nizivo\/react\/([a-z0-9-]+)$/.exec(from)?.[1];
  if (react !== undefined && reactPaths.has(react)) return from;
  if (from === '@nizivo/charts') return from;
  const charts = /^@nizivo\/charts\/([a-z0-9-]+)$/.exec(from)?.[1];
  if (charts !== undefined && chartsPaths.has(charts)) return from;
  return fail(
    file,
    `a pattern may import '${from}' only if it is a public entry: @nizivo/react/<subpath>, ` +
      '@nizivo/charts or @nizivo/charts/<part>, @nizivo/icons or @nizivo/icons/brands/<name>, ' +
      'and react. A pattern is app code: ' +
      'it never imports package source or another pattern.',
  );
}

/**
 * The patterns: `examples/<name>.example.tsx` (the module a pattern route imports, unchanged),
 * `snippets/<name>/<Export>.tsx` (each snippet on its own, for the typecheck) and `manifest.json`,
 * all relative to .generated/patterns/.
 */
export function generatePatternsExamples(): {
  files: Map<string, string>;
  manifest: ExampleManifest;
} {
  const files = new Map<string, string>();
  const manifest: ExampleManifest = {};
  const reactPaths = new Set(reactSubpaths());
  const chartsPaths = new Set(
    Object.keys(chartsExports())
      .filter((k) => k.startsWith('./') && !/\.[a-z]+$/.test(k))
      .map((k) => k.slice(2)),
  );
  for (const name of patternNames()) {
    const file = join(patternsRoot, 'src', name, `${name}.example.tsx`);
    if (!existsSync(file)) fail(file, `the pattern '${name}' has no ${name}.example.tsx`);
    const { module, entry } = exampleFile(file, name, PATTERNS_HEADER, (from) =>
      checkPatternSpecifier(file, from, reactPaths, chartsPaths),
    );
    files.set(`examples/${name}.example.tsx`, module);
    for (const e of entry.examples) {
      files.set(`snippets/${name}/${e.export}.tsx`, `${PATTERNS_HEADER}\n${e.code}`);
    }
    manifest[name] = entry;
  }
  files.set('manifest.json', `${JSON.stringify(manifest, null, 2)}\n`);
  return { files, manifest };
}
