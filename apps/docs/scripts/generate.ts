// Writes the generated parts of the docs app before every build (package.json `build`, `dev`,
// `typecheck`), all from @nizivo/react's exports map, so a new subpath needs no hand edit:
// - .generated/examples/: every packages/react example with public imports, plus the snippet
//   manifest (scripts/examples.ts);
// - .generated/nizivo.css: one `@import … layer(components)` per stylesheet in the exports map, after
//   @nizivo/tokens/tokens.css, in the order the Tailwind recipe documents (ARCHITECTURE.md §7.8);
// - app/docs/(generated)/components/<name>/page.tsx: one route per component. Each route imports only
//   its own example module, so a page loads only the client modules its examples render: the Badge
//   page ships no Nizivo JavaScript and React Aria loads only where Select, Tooltip or Dialog render.
//   One catch-all route for every component would put every example's client modules on every page,
//   because Next builds one client bundle per route from all the client references it imports;
// - .generated/icons/: the Icons page's sprite and index, from the built @nizivo/icons
//   (scripts/icons.ts);
// - .generated/charts/: every packages/charts example with public imports, each snippet as its own
//   module (so the typecheck compiles every snippet a page shows) and the snippet manifest
//   (scripts/examples.ts), plus routes.json, the charts pages that have their own route;
// - app/docs/(generated)/charts/<part>/page.tsx: one route per charts part that has a page in
//   content/docs/charts/. The route renders that MDX page with its own example module, so a chart's
//   client modules load only where it renders: AreaChart's ChartInteraction island ships on the
//   AreaChart page, not on every page of the site (a hand-written MDX page's imports join the one
//   server graph every route shares, .source/server). The MDX names the examples without importing
//   them (components/charts-route.tsx supplies ChartExample and the generated tables);
// - .generated/patterns/ and app/docs/(generated)/patterns/<name>/page.tsx: the same for the patterns
//   (repo-root patterns/, MIT), one route per pattern with a page in content/docs/patterns/, plus
//   .generated/patterns.css, one `@import … layer(components)` per pattern stylesheet, which
//   app/global.css imports after nizivo.css (each sheet writes into nz.patterns).
// `--check` exits 1 when a generated file is stale instead of writing.
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import {
  ExampleError,
  generateChartsExamples,
  generateExamples,
  generatePatternsExamples,
  patternNames,
  patternStylesheet,
  reactExports,
  reactSubpaths,
} from './examples.ts';
import { generateIcons } from './icons.ts';

const docsRoot = join(import.meta.dirname, '..');
const repoRoot = join(docsRoot, '..', '..');
const reactRoot = join(repoRoot, 'packages', 'react');

/** Folders this script owns entirely: it deletes them before writing. */
const OUT_DIRS = [join(docsRoot, '.generated'), join(docsRoot, 'app', 'docs', '(generated)')];

const HEADER =
  'generated by apps/docs/scripts/generate.ts from the @nizivo/react exports map; do not edit';
const CHARTS_HEADER =
  'generated by apps/docs/scripts/generate.ts from packages/charts and content/docs/charts; do not edit';
const PATTERNS_HEADER =
  'generated by apps/docs/scripts/generate.ts from patterns and content/docs/patterns; do not edit';

function stylesheets(): string {
  const sheets = Object.keys(reactExports()).filter(
    (k) => k.startsWith('./css/') && k.endsWith('.css'),
  );
  if (!sheets.includes('./css/base.css')) {
    throw new ExampleError('@nizivo/react exports no ./css/base.css');
  }
  const ordered = ['./css/base.css', ...sheets.filter((s) => s !== './css/base.css')];
  return [
    `/* ${HEADER} */`,
    "@import '@nizivo/tokens/tokens.css' layer(components);",
    ...ordered.map((s) => `@import '@nizivo/react/${s.slice(2)}' layer(components);`),
    '',
  ].join('\n');
}

/** A component is a subpath with a component.json (the same rule as lib/catalog.ts). */
function components(): string[] {
  return reactSubpaths().filter(
    (name) => !name.includes('/') && existsSync(join(reactRoot, 'src', name, 'component.json')),
  );
}

function route(name: string, hasExamples: boolean): string {
  const up = '../../../../../';
  return [
    `// ${HEADER}`,
    "import type { Metadata } from 'next';",
    "import type { JSX } from 'react';",
    ...(hasExamples
      ? [`import * as examples from '${up}.generated/examples/${name}.example';`]
      : []),
    `import { ComponentRoute, componentMetadata } from '${up}components/component-route';`,
    '',
    'export default function Page(): JSX.Element {',
    `  return <ComponentRoute name="${name}" examples={${hasExamples ? 'examples' : '{}'}} />;`,
    '}',
    '',
    'export function generateMetadata(): Metadata {',
    `  return componentMetadata('${name}');`,
    '}',
    '',
  ].join('\n');
}

/** The charts parts with a hand-written page, content/docs/charts/<part>.mdx (not the index). */
function chartsPages(): string[] {
  const dir = join(docsRoot, 'content', 'docs', 'charts');
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((f) => f.endsWith('.mdx') && f !== 'index.mdx')
    .map((f) => f.slice(0, -'.mdx'.length))
    .toSorted();
}

function chartsRoute(part: string, hasExamples: boolean, snippets: readonly string[]): string {
  const up = '../../../../../';
  return [
    // tsc skips dot-folders such as .generated/ unless a file of the program references them, so
    // the route names each snippet module: the docs typecheck and `next build` compile every
    // snippet this page shows. A reference is a comment to the bundler, which loads none of them.
    ...snippets.map(
      (s) => `/// <reference path="${up}.generated/charts/snippets/${part}/${s}.tsx" />`,
    ),
    `// ${CHARTS_HEADER}`,
    "import type { Metadata } from 'next';",
    "import type { JSX } from 'react';",
    ...(hasExamples
      ? [`import * as examples from '${up}.generated/charts/examples/${part}.example';`]
      : []),
    `import { ChartsRoute, chartsMetadata } from '${up}components/charts-route';`,
    '',
    'export default function Page(): JSX.Element {',
    `  return <ChartsRoute part="${part}" examples={${hasExamples ? 'examples' : '{}'}} />;`,
    '}',
    '',
    'export function generateMetadata(): Metadata {',
    `  return chartsMetadata('${part}');`,
    '}',
    '',
  ].join('\n');
}

/** The pattern stylesheets, in the docs' one stylesheet after every package sheet (app/global.css). */
function patternsCss(): string {
  return [
    `/* ${PATTERNS_HEADER} */`,
    ...patternNames()
      .map(patternStylesheet)
      .filter((f) => f !== undefined)
      .map((f) => `@import '../../../${f}' layer(components);`),
    '',
  ].join('\n');
}

/** The patterns with a hand-written page, content/docs/patterns/<name>.mdx (not the index). */
function patternPages(): string[] {
  const dir = join(docsRoot, 'content', 'docs', 'patterns');
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((f) => f.endsWith('.mdx') && f !== 'index.mdx')
    .map((f) => f.slice(0, -'.mdx'.length))
    .toSorted();
}

function patternRoute(name: string, snippets: readonly string[]): string {
  const up = '../../../../../';
  return [
    // as chartsRoute: the references make the typecheck and `next build` compile every snippet
    ...snippets.map(
      (s) => `/// <reference path="${up}.generated/patterns/snippets/${name}/${s}.tsx" />`,
    ),
    `// ${PATTERNS_HEADER}`,
    "import type { Metadata } from 'next';",
    "import type { JSX } from 'react';",
    `import * as examples from '${up}.generated/patterns/examples/${name}.example';`,
    `import { PatternsRoute, patternsMetadata } from '${up}components/patterns-route';`,
    '',
    'export default function Page(): JSX.Element {',
    `  return <PatternsRoute name="${name}" examples={examples} />;`,
    '}',
    '',
    'export function generateMetadata(): Metadata {',
    `  return patternsMetadata('${name}');`,
    '}',
    '',
  ].join('\n');
}

function listFiles(dir: string): string[] {
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { recursive: true, withFileTypes: true })
    .filter((e) => e.isFile())
    .map((e) => join(e.parentPath, e.name));
}

async function main(): Promise<void> {
  const check = process.argv.includes('--check');
  /** Absolute path → text. */
  const files = new Map<string, string>();
  try {
    const { files: examples, manifest } = generateExamples();
    for (const [f, text] of examples) files.set(join(docsRoot, '.generated', 'examples', f), text);
    files.set(join(docsRoot, '.generated', 'nizivo.css'), stylesheets());
    const names = components();
    for (const name of names) {
      files.set(
        join(docsRoot, 'app', 'docs', '(generated)', 'components', name, 'page.tsx'),
        // a page whose examples are all source only imports none of them: Toast's use hooks, which
        // a Server Component route cannot import
        route(name, manifest[name]?.examples.some((example) => example.live) === true),
      );
    }
    const charts = generateChartsExamples();
    for (const [f, text] of charts.files)
      files.set(join(docsRoot, '.generated', 'charts', f), text);
    const chartRoutes = chartsPages();
    for (const part of chartRoutes) {
      files.set(
        join(docsRoot, 'app', 'docs', '(generated)', 'charts', part, 'page.tsx'),
        chartsRoute(
          part,
          charts.manifest[part] !== undefined,
          (charts.manifest[part]?.examples ?? []).map((e) => e.export),
        ),
      );
    }
    files.set(
      join(docsRoot, '.generated', 'charts', 'routes.json'),
      `${JSON.stringify(chartRoutes)}\n`,
    );
    const patterns = generatePatternsExamples();
    for (const [f, text] of patterns.files) {
      files.set(join(docsRoot, '.generated', 'patterns', f), text);
    }
    const patternRoutes = patternPages();
    for (const name of patternRoutes) {
      if (patterns.manifest[name] === undefined) {
        throw new ExampleError(
          `content/docs/patterns/${name}.mdx has no pattern: patterns/src/${name}/ is missing`,
        );
      }
    }
    for (const name of Object.keys(patterns.manifest)) {
      if (!patternRoutes.includes(name)) {
        throw new ExampleError(
          `the pattern '${name}' has no page content/docs/patterns/${name}.mdx`,
        );
      }
      files.set(
        join(docsRoot, 'app', 'docs', '(generated)', 'patterns', name, 'page.tsx'),
        patternRoute(
          name,
          (patterns.manifest[name]?.examples ?? []).map((e) => e.export),
        ),
      );
    }
    files.set(
      join(docsRoot, '.generated', 'patterns', 'routes.json'),
      `${JSON.stringify(patternRoutes)}\n`,
    );
    files.set(join(docsRoot, '.generated', 'patterns.css'), patternsCss());
    const icons = await generateIcons(repoRoot);
    files.set(join(docsRoot, '.generated', 'icons', 'sprite.svg'), icons.sprite);
    files.set(
      join(docsRoot, '.generated', 'icons', 'index.json'),
      `${JSON.stringify(icons.index)}\n`,
    );
    const count = Object.values(manifest).reduce((n, f) => n + f.examples.length, 0);
    if (!check) {
      console.log(
        `generate: ${count} examples from ${Object.keys(manifest).length} files, ` +
          `${names.length} component routes, nizivo.css, ${icons.index.length} icons, ` +
          `${Object.values(charts.manifest).reduce((n, f) => n + f.examples.length, 0)} charts ` +
          `examples, ${chartRoutes.length} charts routes and ${patternRoutes.length} patterns`,
      );
    }
  } catch (error) {
    if (error instanceof ExampleError) {
      console.error(`generate: ${error.message}`);
      process.exit(1);
    }
    throw error;
  }
  if (check) {
    const stale = [...files]
      .filter(([p, text]) => !existsSync(p) || readFileSync(p, 'utf8') !== text)
      .map(([p]) => relative(docsRoot, p));
    const extra = OUT_DIRS.flatMap(listFiles)
      .filter((p) => !files.has(p))
      .map((p) => relative(docsRoot, p));
    if (stale.length > 0 || extra.length > 0) {
      console.error(`generate: stale: ${[...stale, ...extra].join(', ')}`);
      process.exit(1);
    }
    return;
  }
  for (const dir of OUT_DIRS) rmSync(dir, { recursive: true, force: true });
  for (const [p, text] of files) {
    mkdirSync(join(p, '..'), { recursive: true });
    writeFileSync(p, text);
  }
}

await main();
